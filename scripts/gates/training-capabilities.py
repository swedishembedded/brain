"""Generate and check docs/reference/training-capabilities.md and the serving
support table compiled into brain_arch (crates/arch/src/support_table.rs).

Both are rendered from scripts/gates/training-capabilities.tsv. Checking
(default) fails when
  - the page or the support table differs from the rendering (`--write`
    regenerates both);
  - a named test does not exist, is not a #[test] function, or is #[ignore]d
    without a (real) or (cuda) flag, or a named file does not exist;
  - a test named in a serving-certification `real` cell carries no (real) or
    (cuda) flag;
  - a declared arch is not rendered in any table, or a capability name is unknown
    (a `load:<source>` row renders in the checkpoint-precision table, a
    `cert:<contract>` row in the training-correctness table);
  - a registration disagrees: each tier registered for a subject in
    crates/rl/tests/conformance.rs needs a lora_<tier> row, and each
    architecture in crates/sdk/src/study.rs registered `with_chat_trainer` needs a
    full_ft row and CHAT_LORA_FINE_TUNE a lora_* row;
  - a catalog entry (crates/catalog/src/lib.rs `models()`) resolves to no
    architecture of crates/arch/src/lib.rs and is not a known pipeline, or a
    serving-certification cell names an architecture the catalog does not serve.
The serving-certification table has one row per architecture the catalog
serves, toy architectures excepted, and derives each row's support level from
its cells (SUPPORT_REQUIRES); the support table carries the same levels for
the model cards a server reports.
That a named test passes is `make test`'s job; this gate keeps the page and the
test names honest.
"""
import argparse
import re
import sys
from pathlib import Path

SERVE_COLS = [("import", "Import"), ("parity", "Forward parity"), ("serve", "Serve"), ("cancel", "Cancel"), ("batch", "Batch"),
              ("quant_serving", "Quantized"), ("real", "Real weights")]
SERVE_CAPS = {c for c, _ in SERVE_COLS}
CAPS = {"full_ft", "lora_f32", "lora_bf16", "lora_int8", "lora_nf4", "lora_fp8", "other", "adapter_serving", "kv_tiers", "load", "certify"} | SERVE_CAPS
# A served architecture is production-supported when every one of these cells
# is certified, and preview otherwise.
SUPPORT_REQUIRES = ("parity", "serve", "cancel", "batch")
# Catalog entries that serve a pipeline over other models, not an architecture.
PIPELINES = {"imgpipe", "imageops", "recon"}
# Catalog modules whose name is not the architecture id they serve.
CATALOG_ALIASES = {"decisions": "decide"}
TIER_CAP = {"bf16": "lora_bf16", "int8": "lora_int8", "nf4": "lora_nf4", "fp8": "lora_fp8", "f32": "lora_f32"}

HEAD = """# Training and serving capability matrix

<!-- Generated by scripts/gates/training-capabilities.py from scripts/gates/training-capabilities.tsv; edit the declaration, not this page. -->

Which architecture can be fine-tuned how, over which checkpoint precision,
and served with adapters and which KV tiers, and which serving contracts each
served architecture is certified for. Every cell names the test that
backs it; a cell with no test is written `-` and means "not offered", never
"untested but probably works". Per-model pages hold the commands. This page
does not record speed or memory figures.

Tests are named `crate/tests/file.rs::test_name` (or `crate/src/file.rs` for a
unit test). A test that needs a real checkpoint or a CUDA card is marked
`(real)` or `(cuda)`; the others run on the CPU backend with random weights.
`gpt2` trains from scratch (see its page) and offers no adapter.

"""
TABLES = [
    ("Language models", ["qwen3", "qwen35", "edgerock", "qwen35moe", "ricursive", "inkling2", "glmdsa", "gpt2"],
     [("full_ft", "Full fine-tune"), ("lora_f32", "LoRA, fp32 base"), ("lora_bf16", "LoRA, bf16 base"),
      ("lora_int8", "LoRA, int8 base"), ("lora_nf4", "LoRA, NF4 base (QLoRA)"), ("lora_fp8", "LoRA, FP8 base"), ("other", "Other")],
     "No architecture offers a full fine-tune over a quantized or fp8 base. Trainable\nparameters, gradients and optimizer moments are held below fp32 only where a\ncell says so.\n"),
    ("Image and video generators", ["flux2", "s3dit", "wan"],
     [("lora_f32", "LoRA, fp32 base"), ("lora_int8", "LoRA, int8 base"), ("other", "Other")], ""),
    ("Perception models", ["mirage"],
     [("full_ft", "Full and head-only fine-tune"), ("lora_f32", "LoRA, fp32 base"), ("adapter_serving", "Adapters while serving")], ""),
    ("Serving adapters and KV tiers", ["qwen3", "qwen35", "qwen35moe", "ricursive"],
     [("adapter_serving", "Adapters while serving"), ("kv_tiers", "KV tiers")], ""),
]
SERVE_HEAD = """## Serving certification

Being registered does not establish that a model serves correctly. One row
per architecture the catalog serves; a cell names the tests that certify it,
and `-` means not certified.

- **Import:** loading validates the checkpoint: full tensor coverage, and a
  missing, unexpected or misshapen tensor or a bad format refused by name.
- **Forward parity:** the forward agrees numerically with an independent
  reference (a golden from `tools/goldens`, or a torch or transformers
  reference), not with another brain path.
- **Serve:** the model loads, generates (streaming where its action streams)
  and is released through its provider or resident; a scheduler engine also
  passes `model::serve::conformance::run_all`.
- **Cancel:** a token fired before the call is refused before any work (the
  catalog proof `catalog/tests/it/cancellation.rs`), or the family's own
  cancellation test.
- **Batch:** requests served together answer what each answers alone.
- **Quantized:** an int8, FP8, NF4 or packed serving tier tracks fp32 within
  the bound its test asserts.
- **Real weights:** a test over a released checkpoint, `(real)` or `(cuda)`.

**Support** is derived from the cells: `production` when """ + ", ".join(dict(SERVE_COLS)[c].lower() for c in SUPPORT_REQUIRES[:-1]) + " and " + dict(SERVE_COLS)[SUPPORT_REQUIRES[-1]].lower() + """
are all certified, `preview` otherwise.

| Architecture | """ + " | ".join(c[1] for c in SERVE_COLS) + """ | Support |
|---|""" + "---|" * (len(SERVE_COLS) + 1)
CERT_HEAD = """## Training correctness

Contracts every training run relies on, each held by the tests named beside
it against an independent reference (an FP64 oracle written from the math,
finite differences, or the uninterrupted run for a resume). A contract with
no row here is not certified.

| Contract | What holds | Tests |
|---|---|---|"""

TAIL = """
A LoRA adapter trains over an FP8 base on qwen3, qwen35 and ricursive. NVFP4
and MX checkpoints have `Weight` storage and execution, and only ricursive's
LoRA trainer offers the NVFP4 release as a base (its "Other" cell). The contributor roadmap for these gaps is
`.agents/roadmap/quantized-training.md`.
"""


def parse(path):
    cells = {}
    for n, line in enumerate(Path(path).read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        p = line.split("\t")
        if len(p) != 4 or p[1] not in CAPS or not p[3].strip():
            sys.exit(f"{path}:{n}: need arch<TAB>capability(one of {sorted(CAPS)})<TAB>detail<TAB>tests")
        tests = []
        for t in p[3].split(";"):
            m = re.fullmatch(r"(\S+?)(?:::(\w+))?(?: \((real|cuda)\))?", t.strip())
            if not m:
                sys.exit(f"{path}:{n}: bad test reference {t!r}")
            tests.append((m.group(1), m.group(2), m.group(3)))
        cells[(p[0], p[1])] = (p[2].strip(), tests)
    return cells


def cell(entry):
    if entry is None:
        return "-"
    detail, tests = entry
    refs = ", ".join(f"`{f}{'::' + n if n else ''}`" + (f" ({fl})" if fl else "") for f, n, fl in tests)
    return f"{detail}: {refs}" if detail else refs


def support(cells, arch):
    return "production" if all((arch, c) in cells for c in SUPPORT_REQUIRES) else "preview"


def render(cells, served):
    out = [HEAD]
    for title, archs, cols, note in TABLES:
        out.append(f"## {title}\n\n| Architecture | " + " | ".join(c[1] for c in cols) + " |\n|---|" + "---|" * len(cols))
        for a in archs:
            out.append(f"| `{a}` | " + " | ".join(cell(cells.get((a, c[0]))) for c in cols) + " |")
        out.append("")
        if note:
            out.append(note)
    out.append(SERVE_HEAD)
    for a in served:
        out.append(f"| `{a}` | " + " | ".join(cell(cells.get((a, c))) for c, _ in SERVE_COLS) + f" | {support(cells, a)} |")
    out.append("")
    out.append("## Checkpoint precision on load\n\n| Source | What stays packed | Test |\n|---|---|---|")
    for (a, c), (detail, tests) in cells.items():
        if a.startswith("load:"):
            refs = ", ".join(f"`{f}{'::' + n if n else ''}`" for f, n, _ in tests)
            out.append(f"| {a[5:]} | {detail} | {refs} |")
    out.append("")
    out.append(CERT_HEAD)
    for (a, c), (detail, tests) in cells.items():
        if a.startswith("cert:"):
            refs = ", ".join(f"`{f}{'::' + n if n else ''}`" + (f" ({fl})" if fl else "") for f, n, fl in tests)
            out.append(f"| {a[5:]} | {detail} | {refs} |")
    out.append(TAIL)
    return "\n".join(out).replace("\n\n\n", "\n\n")


TABLE_HEAD = """// SPDX-License-Identifier: Apache-2.0
// Copyright (c) 2026 Martin Schröder <info@swedishembedded.com>

// Generated by scripts/gates/training-capabilities.py from
// scripts/gates/training-capabilities.tsv; edit the declaration, not this file.

//! The serving support level of every architecture the catalog serves, as the
//! capability matrix's serving-certification table derives it.

use crate::support::Support;

/// `(architecture id, support level)`, in registry order.
pub(crate) const SERVING: &[(&str, Support)] = &[
"""


def render_table(cells, served):
    rows = "".join(f'    ("{a}", Support::{support(cells, a).capitalize()}),\n' for a in served)
    return TABLE_HEAD + rows + "];\n"


def check_tests(cells, root):
    problems = []
    for (arch, cap), (_, tests) in cells.items():
        for f, name, flag in tests:
            path = root / "crates" / f
            if not path.is_file():
                problems.append(f"MISSING FILE: {arch}/{cap}: crates/{f}")
                continue
            if name is None:
                continue
            lines = path.read_text().splitlines()
            idx = [i for i, l in enumerate(lines) if re.search(rf"\bfn {re.escape(name)}\s*[(<]", l)]
            if not idx:
                problems.append(f"MISSING TEST: {arch}/{cap}: no `fn {name}` in crates/{f}")
                continue
            attrs = " ".join(lines[max(0, idx[0] - 6): idx[0]])
            if "#[test]" not in attrs and "#[tokio::test]" not in attrs:
                problems.append(f"NOT A TEST: {arch}/{cap}: `fn {name}` in crates/{f} has no #[test]")
            if "#[ignore" in attrs and not flag:
                problems.append(f"IGNORED TEST: {arch}/{cap}: `{name}` in crates/{f} is #[ignore]d; flag it (real) or (cuda) or name another test")
        if cap == "real":
            problems += [f"UNFLAGGED REAL: {arch}/real: crates/{f}{'::' + n if n else ''} needs a (real) or (cuda) flag" for f, n, flag in tests if not flag]
    return problems


def registry(root):
    """The architecture ids of crates/arch/src/lib.rs in registry order, and the toy ones among them."""
    path = root / "crates/arch/src/lib.rs"
    if not path.exists():
        return [], set()
    rows = re.findall(r'arch!\(\s*"([a-z0-9]+)",\s*"[^"]*",\s*([\w:]+)', path.read_text())
    return [a for a, _ in rows], {a for a, d in rows if d.split("::")[-1] == "Toy"}


def served_families(root):
    """Every architecture the catalog serves, in registry order, and the entries that resolve to none; `None` for a
    tree with no catalog.

    An entry `manifest: <module>::...::<fn>` names its architecture by its module (`qwen3::caps::manifest`), by
    the module with `resident_` dropped (`resident_ouro::direct_manifest`), or by the leading word of its function
    (`resident_forecast::chronos2_direct_manifest`)."""
    path = root / "crates/catalog/src/lib.rs"
    if not path.exists():
        return None, []
    archs, toys = registry(root)
    body = path.read_text().split("pub fn models()", 1)[-1].split("\n}\n", 1)[0]
    served, unresolved = [], []
    for entry in re.findall(r"manifest: ([\w:]+)", body):
        parts = entry.split("::")
        module = CATALOG_ALIASES.get(parts[0], parts[0])
        arch = next((c for c in (module, module.removeprefix("resident_"), parts[-1].split("_")[0]) if c in archs), None)
        if arch is None:
            if module not in PIPELINES:
                unresolved.append(entry)
        elif arch not in toys and arch not in served:
            served.append(arch)
    return sorted(served, key=archs.index), unresolved


def check_registrations(cells, root, catalog):
    problems = []
    have = {k for k in cells}
    conf = root / "crates/rl/tests/conformance.rs"
    if conf.exists():
        subject = None
        for line in conf.read_text().splitlines():
            m = re.search(r'name: "(\w+)",$', line.strip()) or re.search(r'Subject \{ name: "(\w+)"', line)
            if m:
                subject = m.group(1)
            for t in re.findall(r'Tier \{ name: "(\w+)"', line):
                cap = TIER_CAP.get(t)
                if subject and (subject, cap) not in have:
                    problems.append(f"UNDECLARED TIER: rl/tests/conformance.rs registers {subject} tier {t} but the declaration has no {subject} {cap} row")
    study = root / "crates/sdk/src/study.rs"
    if study.exists():
        text = study.read_text()
        chat_rows = set(re.findall(r"ArchEntry::of::<(\w+)>\(\)\s*\.with_chat_trainer", text))
        for block in re.split(r"impl StudyArch for ", text)[1:]:
            struct = re.match(r"(\w+)", block).group(1)
            block = block.split("fn study_config")[0]
            ident = re.search(r'const ID: &\'static str = "(\w+)"', block)
            if not ident:
                continue
            a = ident.group(1)
            if struct in chat_rows and (a, "full_ft") not in have:
                problems.append(f"UNDECLARED CAPABILITY: sdk study.rs registers a chat trainer for {a} but there is no {a} full_ft row")
            if re.search(r"const CHAT_LORA_FINE_TUNE: bool = true", block) and not any(k[0] == a and k[1].startswith("lora_") for k in have):
                problems.append(f"UNDECLARED CAPABILITY: sdk study.rs declares {a} CHAT_LORA_FINE_TUNE but there is no {a} lora_* row")
    rendered = {a for _, archs, _, _ in TABLES for a in archs}
    for a, c in sorted(have):
        if c in SERVE_CAPS:
            if catalog is not None and a not in catalog:
                problems.append(f"NOT SERVED: {a} {c} certifies serving, but the catalog serves no {a}")
        elif not a.startswith(("load:", "cert:")) and a not in rendered:
            problems.append(f"NOT RENDERED: {a} {c} is declared but {a} is in no table; add it to TABLES")
    return problems


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(here.parent.parent))
    ap.add_argument("--decl", default=str(here / "training-capabilities.tsv"))
    ap.add_argument("--page", default="docs/reference/training-capabilities.md")
    ap.add_argument("--table", default="crates/arch/src/support_table.rs")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    root = Path(a.root)
    cells = parse(a.decl)
    page = root / a.page
    catalog, unresolved = served_families(root)
    # With no catalog (a synthetic tree), the rows are the architectures that certify anything.
    served = catalog if catalog is not None else sorted({arch for arch, c in cells if c in SERVE_CAPS})
    text = render(cells, served)
    table, table_text = root / a.table, render_table(cells, served)
    if a.write:
        page.write_text(text)
        table.parent.mkdir(parents=True, exist_ok=True)
        table.write_text(table_text)
        print(f"training-capabilities: wrote {a.page} and {a.table}")
        return 0
    problems = check_tests(cells, root) + check_registrations(cells, root, catalog)
    problems += [f"UNRESOLVED CATALOG ENTRY: crates/catalog/src/lib.rs serves `{e}`, which names no architecture of crates/arch/src/lib.rs; register it, or list it in PIPELINES or CATALOG_ALIASES" for e in unresolved]
    if not page.exists() or page.read_text() != text:
        problems.append(f"DRIFT: {a.page} differs from the declaration; run scripts/gates/training-capabilities.py --write")
    if not table.exists() or table.read_text() != table_text:
        problems.append(f"DRIFT: {a.table} differs from the declaration; run scripts/gates/training-capabilities.py --write")
    if problems:
        print("\n".join(problems))
        print(f"training-capabilities: FAIL ({len(problems)} problem(s))")
        return 1
    print(f"training-capabilities: OK, {len(cells)} declared cell(s), every test present")
    return 0


if __name__ == "__main__":
    sys.exit(main())
