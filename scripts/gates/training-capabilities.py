"""Generate and check docs/reference/training-capabilities.md.

The page is rendered from scripts/gates/training-capabilities.tsv. Checking
(default) fails when
  - the page differs from the rendering (`--write` regenerates it);
  - a named test does not exist, is not a #[test] function, or is #[ignore]d
    without a (real) or (cuda) flag, or a named file does not exist;
  - a declared arch is not rendered in any table, or a capability name is unknown;
  - a registration disagrees: each tier registered for a subject in
    crates/rl/tests/conformance.rs needs a lora_<tier> row, and each
    architecture in crates/sdk/src/study.rs registered `with_chat_trainer` needs a
    full_ft row and CHAT_LORA_FINE_TUNE a lora_* row.
That a named test passes is `make test`'s job; this gate keeps the page and the
test names honest.
"""
import argparse
import re
import sys
from pathlib import Path

CAPS = {"full_ft", "lora_f32", "lora_bf16", "lora_int8", "lora_nf4", "lora_fp8", "other", "adapter_serving", "quant_serving", "kv_tiers", "load"}
TIER_CAP = {"bf16": "lora_bf16", "int8": "lora_int8", "nf4": "lora_nf4", "fp8": "lora_fp8", "f32": "lora_f32"}

HEAD = """# Training and serving capability matrix

<!-- Generated by scripts/gates/training-capabilities.py from scripts/gates/training-capabilities.tsv; edit the declaration, not this page. -->

Which architecture can be fine-tuned how, over which checkpoint precision,
and served with adapters and which KV tiers. Every cell names the test that
backs it; a cell with no test is written `-` and means "not offered", never
"untested but probably works". Per-model pages hold the commands. This page
does not record speed or memory figures.

Tests are named `crate/tests/file.rs::test_name` (or `crate/src/file.rs` for a
unit test). A test that needs a real checkpoint or a CUDA card is marked
`(real)` or `(cuda)`; the others run on the CPU backend with random weights.
`gpt2` trains from scratch (see its page) and offers no adapter.

"""
TABLES = [
    ("Language models", ["qwen3", "qwen35", "qwen35moe", "glmdsa", "gpt2"],
     [("full_ft", "Full fine-tune"), ("lora_f32", "LoRA, fp32 base"), ("lora_bf16", "LoRA, bf16 base"),
      ("lora_int8", "LoRA, int8 base"), ("lora_nf4", "LoRA, NF4 base (QLoRA)"), ("lora_fp8", "LoRA, FP8 base"), ("other", "Other")],
     "No architecture offers a full fine-tune over a quantized or fp8 base. Trainable\nparameters, gradients and optimizer moments are held below fp32 only where a\ncell says so.\n"),
    ("Image and video generators", ["flux2", "s3dit", "wan"],
     [("lora_f32", "LoRA, fp32 base"), ("lora_int8", "LoRA, int8 base"), ("other", "Other")], ""),
    ("Serving adapters and KV tiers", ["qwen3", "qwen35", "qwen35moe"],
     [("adapter_serving", "Adapters while serving"), ("quant_serving", "Quantized weights while serving"), ("kv_tiers", "KV tiers")], ""),
]
TAIL = """
A LoRA adapter trains over an FP8 base on qwen3 and qwen35. NVFP4 and MX
checkpoints have `Weight` storage and execution but no model's LoRA trainer
offers them as a base yet. The contributor roadmap for these gaps is
`.agents/roadmap/quantized-training.md`.
"""


def parse(path):
    cells = {}
    for n, line in enumerate(Path(path).read_text().splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        p = line.split("\t")
        if len(p) != 4 or p[1] not in CAPS or not p[3].strip():
            sys.exit(f"{path}:{n}: need arch<TAB>capability(one of {sorted(CAPS)})<TAB>detail<TAB>tests")
        tests = []
        for t in p[3].split(";"):
            m = re.fullmatch(r"(\S+?)(?:::(\w+))?(?: \((real|cuda)\))?", t.strip())
            if not m:
                sys.exit(f"{path}:{n}: bad test reference {t!r}")
            tests.append((m.group(1), m.group(2), m.group(3)))
        cells[(p[0], p[1])] = (p[2].strip(), tests)
    return cells


def cell(entry):
    if entry is None:
        return "-"
    detail, tests = entry
    refs = ", ".join(f"`{f}{'::' + n if n else ''}`" + (f" ({fl})" if fl else "") for f, n, fl in tests)
    return f"{detail}: {refs}" if detail else refs


def render(cells):
    out = [HEAD]
    for title, archs, cols, note in TABLES:
        out.append(f"## {title}\n\n| Architecture | " + " | ".join(c[1] for c in cols) + " |\n|---|" + "---|" * len(cols))
        for a in archs:
            out.append(f"| `{a}` | " + " | ".join(cell(cells.get((a, c[0]))) for c in cols) + " |")
        out.append("")
        if note:
            out.append(note)
    out.append("## Checkpoint precision on load\n\n| Source | What stays packed | Test |\n|---|---|---|")
    for (a, c), (detail, tests) in cells.items():
        if a.startswith("load:"):
            refs = ", ".join(f"`{f}{'::' + n if n else ''}`" for f, n, _ in tests)
            out.append(f"| {a[5:]} | {detail} | {refs} |")
    out.append(TAIL)
    return "\n".join(out).replace("\n\n\n", "\n\n")


def check_tests(cells, root):
    problems = []
    for (arch, cap), (_, tests) in cells.items():
        for f, name, flag in tests:
            path = root / "crates" / f
            if not path.is_file():
                problems.append(f"MISSING FILE: {arch}/{cap}: crates/{f}")
                continue
            if name is None:
                continue
            lines = path.read_text().splitlines()
            idx = [i for i, l in enumerate(lines) if re.search(rf"\bfn {re.escape(name)}\s*[(<]", l)]
            if not idx:
                problems.append(f"MISSING TEST: {arch}/{cap}: no `fn {name}` in crates/{f}")
                continue
            attrs = " ".join(lines[max(0, idx[0] - 6): idx[0]])
            if "#[test]" not in attrs and "#[tokio::test]" not in attrs:
                problems.append(f"NOT A TEST: {arch}/{cap}: `fn {name}` in crates/{f} has no #[test]")
            if "#[ignore" in attrs and not flag:
                problems.append(f"IGNORED TEST: {arch}/{cap}: `{name}` in crates/{f} is #[ignore]d; flag it (real) or (cuda) or name another test")
    return problems


def check_registrations(cells, root):
    problems = []
    have = {k for k in cells}
    conf = root / "crates/rl/tests/conformance.rs"
    if conf.exists():
        subject = None
        for line in conf.read_text().splitlines():
            m = re.search(r'name: "(\w+)",$', line.strip()) or re.search(r'Subject \{ name: "(\w+)"', line)
            if m:
                subject = m.group(1)
            for t in re.findall(r'Tier \{ name: "(\w+)"', line):
                cap = TIER_CAP.get(t)
                if subject and (subject, cap) not in have:
                    problems.append(f"UNDECLARED TIER: rl/tests/conformance.rs registers {subject} tier {t} but the declaration has no {subject} {cap} row")
    study = root / "crates/sdk/src/study.rs"
    if study.exists():
        text = study.read_text()
        chat_rows = set(re.findall(r"ArchEntry::of::<(\w+)>\(\)\s*\.with_chat_trainer", text))
        for block in re.split(r"impl StudyArch for ", text)[1:]:
            struct = re.match(r"(\w+)", block).group(1)
            block = block.split("fn study_config")[0]
            ident = re.search(r'const ID: &\'static str = "(\w+)"', block)
            if not ident:
                continue
            a = ident.group(1)
            if struct in chat_rows and (a, "full_ft") not in have:
                problems.append(f"UNDECLARED CAPABILITY: sdk study.rs registers a chat trainer for {a} but there is no {a} full_ft row")
            if re.search(r"const CHAT_LORA_FINE_TUNE: bool = true", block) and not any(k[0] == a and k[1].startswith("lora_") for k in have):
                problems.append(f"UNDECLARED CAPABILITY: sdk study.rs declares {a} CHAT_LORA_FINE_TUNE but there is no {a} lora_* row")
    rendered = {a for _, archs, _, _ in TABLES for a in archs}
    for a, c in sorted(have):
        if not a.startswith("load:") and a not in rendered:
            problems.append(f"NOT RENDERED: {a} {c} is declared but {a} is in no table; add it to TABLES")
    return problems


def main():
    here = Path(__file__).resolve().parent
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=str(here.parent.parent))
    ap.add_argument("--decl", default=str(here / "training-capabilities.tsv"))
    ap.add_argument("--page", default="docs/reference/training-capabilities.md")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    root = Path(a.root)
    cells = parse(a.decl)
    page = root / a.page
    text = render(cells)
    if a.write:
        page.write_text(text)
        print(f"training-capabilities: wrote {a.page}")
        return 0
    problems = check_tests(cells, root) + check_registrations(cells, root)
    if not page.exists() or page.read_text() != text:
        problems.append(f"DRIFT: {a.page} differs from the declaration; run scripts/gates/training-capabilities.py --write")
    if problems:
        print("\n".join(problems))
        print(f"training-capabilities: FAIL ({len(problems)} problem(s))")
        return 1
    print(f"training-capabilities: OK, {len(cells)} declared cell(s), every test present")
    return 0


if __name__ == "__main__":
    sys.exit(main())
