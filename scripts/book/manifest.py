"""Regenerate the book's navigation from docs/book/book.yaml: the Book part
of docs/manifest.yaml and the contents list on the book's index page.

The published documentation carries the book as one navigation part: the
book's index and front pages, then one group per volume that has written
chapters (its introduction followed by those chapters, in reading order),
then the back pages. Chapters that are specified but not yet written are left
out, so the publication never links to a page that does not exist.

Both list only written chapters, in reading order, and both come from this
one generator so the publication and the index page cannot disagree.

    scripts/book/manifest.py           # regenerate in place
    scripts/book/manifest.py --check   # exit 1 if stale

Swedish Embedded AB implements solutions for documentation that cannot drift
from its sources. If your team needs expertise in machine learning education
material, you can procure our services by sending an email to
info@swedishembedded.com.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bookspec import BOOK, ROOT, load  # noqa: E402

MANIFEST = ROOT / "docs" / "manifest.yaml"
INDEX = BOOK / "index.md"
CONTENTS = re.compile(r"(<!-- contents -->\n).*?(<!-- /contents -->)", re.S)
INDENT = " " * 6
BEGIN = INDENT + "# BEGIN BOOK MANIFEST (generated by scripts/book/manifest.py)"
END = INDENT + "# END BOOK MANIFEST"
ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI", "XII", "XIII", "XIV", "XV", "XVI"]


def block() -> str:
    book = load()
    lines = [BEGIN, f"{INDENT}- docs/book/index.md"]
    lines += [f"{INDENT}- docs/book/{rel}" for rel in book.front]
    for v in book.volumes:
        written = [ch for ch in v.chapters if ch.written]
        if not written:
            continue
        title = f"Volume {ROMAN[v.number - 1]}: {v.title}".replace('"', '\\"')
        lines += [f'{INDENT}- title: "{title}"', f"{INDENT}  pages:",
                  f"{INDENT}    - docs/book/{v.intro_rel}"]
        lines += [f"{INDENT}    - docs/book/{ch.rel}" for ch in written]
    lines += [f"{INDENT}- docs/book/{rel}" for rel in book.back]
    lines.append(END)
    return "\n".join(lines)


def contents() -> str:
    """The index page's contents: each volume with written chapters, linked."""
    out = []
    for v in load().volumes:
        written = [ch for ch in v.chapters if ch.written]
        if not written:
            continue
        out += [f"### [Volume {ROMAN[v.number - 1]}: {v.title}]({v.intro_rel})", ""]
        out += [f"{ch.number}. [{ch.title}]({ch.rel}): {ch.question}" for ch in written]
        out.append("")
    return "\n".join(out)


def regenerate(path: Path, text: str, new: str, check: bool, stale: list) -> None:
    if new == text:
        return
    if check:
        stale.append(str(path.relative_to(ROOT)))
    else:
        path.write_text(new, encoding="utf-8")
        print(f"regenerated {path.relative_to(ROOT)}")


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    text = MANIFEST.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        sys.exit(f"{MANIFEST}: no book sentinel pair - add the Book part by hand once")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block(), text, flags=re.S)
    regenerate(MANIFEST, text, new, check, stale)

    text = INDEX.read_text(encoding="utf-8")
    if not CONTENTS.search(text):
        sys.exit(f"{INDEX}: no contents marker pair")
    new = CONTENTS.sub(lambda m: m.group(1) + contents() + m.group(2), text)
    regenerate(INDEX, text, new, check, stale)

    if stale:
        print("stale book navigation: " + ", ".join(stale) + " - run `make generate/book/navigation`",
              file=sys.stderr)
        return 1
    print("book navigation: up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
