"""Geometry check for the book's rendered SVG figures: nothing may overflow.

A figure can be valid SVG, render without warnings and still be wrong to
look at: a label wider than its box, a box hanging over the edge of its
panel, a caption cut off at the canvas edge. This module reads a rendered
SVG and checks, with text measured by the advance widths of the face every
renderer of the book resolves its sans-serif to (Helvetica, or its metric
twins Nimbus Sans, Arial and Liberation Sans):

* every text line lies inside the canvas;
* every text line that starts inside a box or an ellipse lies inside it, with
  a margin;
* every box that is centred inside a larger box (a panel or a group) lies
  inside it, and every box and ellipse lies inside the canvas.

Graphviz output is not checked: Graphviz sizes its own nodes.

Swedish Embedded AB implements solutions for clear technical communication.
If your team needs expertise in machine learning education material, you can
procure our services by sending an email to info@swedishembedded.com.
"""
import re
import xml.etree.ElementTree as ET

# Helvetica advance widths, in thousandths of the font size (Adobe AFM).
_ADV = dict(zip(
    " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~",
    [278, 278, 355, 556, 556, 889, 667, 191, 333, 333, 389, 584, 278, 333, 278, 278]
    + [556] * 10
    + [278, 278, 584, 584, 584, 556, 1015, 667, 667, 722, 722, 667, 611, 778, 722, 278, 500, 667, 556, 833, 722,
       778, 667, 778, 722, 667, 611, 722, 667, 944, 667, 667, 611, 278, 278, 278, 469, 556, 333, 556, 556, 500,
       556, 556, 278, 556, 556, 222, 222, 500, 222, 833, 556, 556, 556, 556, 333, 500, 278, 556, 500, 722, 500,
       500, 500, 334, 260, 334, 584]))
_WIDE = 650  # a glyph outside ASCII (Greek, arrows, math): a generous average
_BOLD = 1.07  # bold Helvetica is about this much wider
TEXT_MARGIN = 4.0  # px a label must keep from the edge of a filled box
ELLIPSE_MARGIN = 1.5  # px inside an ellipse (a symbol in a small circle)
SLACK = 0.5  # px of rounding tolerated in containment


def text_width(s: str, size: float, bold: bool = False) -> float:
    """Advance width in px of `s` set in Helvetica at `size` px."""
    w = sum(_ADV.get(c, _WIDE) for c in s) * size / 1000
    return w * _BOLD if bold else w


def _num(v, default=0.0):
    if v is None:
        return default
    m = re.match(r"\s*(-?[\d.]+(?:e-?\d+)?)", v)
    return float(m.group(1)) if m else default


def _strip(tag):
    return tag.rsplit("}", 1)[-1]


def _walk(el, dx=0.0, dy=0.0, clipped=False):
    """Yield (element, dx, dy, clipped) with the translate() offsets of the
    enclosing groups and whether a clip path bounds what it draws."""
    clipped = clipped or el.get("clip-path") is not None
    tr = el.get("transform", "")
    m = re.match(r"\s*translate\(\s*(-?[\d.]+)[ ,]+(-?[\d.]+)\s*\)", tr)
    if m:
        dx, dy = dx + float(m.group(1)), dy + float(m.group(2))
    elif tr.strip():
        return  # rotated or scaled content: not measured
    yield el, dx, dy, clipped
    if _strip(el.tag) in ("defs", "marker", "clipPath"):
        return
    for child in el:
        yield from _walk(child, dx, dy, clipped)


def problems(svg: str) -> list[str]:
    """Every overflow in the SVG document `svg`, as readable lines."""
    if "<!-- Generated by graphviz" in svg or 'class="graph"' in svg:
        return []
    root = ET.fromstring(re.sub(r"<!--.*?-->", "", svg, flags=re.S))
    vb = [float(v) for v in root.get("viewBox", "0 0 0 0").split()]
    W, H = (vb[2], vb[3]) if len(vb) == 4 and vb[2] else (_num(root.get("width")), _num(root.get("height")))
    rects, ells, texts, frames = [], [], [], []
    for el, dx, dy, clipped in _walk(root):
        tag = _strip(el.tag)
        if tag == "rect":
            x, y, w, h = (_num(el.get(k)) + o for k, o in (("x", dx), ("y", dy), ("width", 0), ("height", 0)))
            if w >= W - 1 and h >= H - 1:
                continue  # the background
            # An unfilled rectangle is a frame (a plot's area, a box drawn as
            # data): it holds neither text nor other boxes, only the canvas
            # bounds it.
            if el.get("fill") == "none":
                frames.append((x, y, x + w, y + h))
                continue
            if w > 0 and h > 0 and not clipped:
                rects.append((x, y, x + w, y + h, TEXT_MARGIN))
        elif tag == "ellipse" or tag == "circle":
            cx, cy = _num(el.get("cx")) + dx, _num(el.get("cy")) + dy
            rx = _num(el.get("rx"), _num(el.get("r")))
            ry = _num(el.get("ry"), _num(el.get("r")))
            if rx > 4 and ry > 4 and not clipped:  # markers and dots are not containers
                ells.append((cx, cy, rx, ry))
        elif tag == "text":
            s = "".join(el.itertext())
            if not s.strip():
                continue
            size = _num(el.get("font-size"), 13)
            bold = el.get("font-weight") in ("bold", "700")
            w = text_width(s, size, bold)
            x, y = _num(el.get("x")) + dx, _num(el.get("y")) + dy
            anchor = el.get("text-anchor", "start")
            x0 = x - w / 2 if anchor == "middle" else x - w if anchor == "end" else x
            texts.append((s, x0, x0 + w, y - 0.72 * size, y + 0.22 * size, x, y))
    out = []
    for s, x0, x1, top, bot, ax, ay in texts:
        if x0 < -SLACK or x1 > W + SLACK or top < -SLACK or bot > H + SLACK:
            out.append(f"text {s!r} runs off the {W:g}x{H:g} canvas (x {x0:.0f}..{x1:.0f})")
            continue
        holders = [r for r in rects if r[0] <= ax <= r[2] and r[1] <= ay <= r[3]]
        if holders:
            r = min(holders, key=lambda r: (r[2] - r[0]) * (r[3] - r[1]))
            if x0 < r[0] + r[4] or x1 > r[2] - r[4]:
                out.append(f"text {s!r} ({x1 - x0:.0f} px) overflows its box {r[2] - r[0]:.0f} px wide at "
                           f"x {r[0]:.0f}..{r[2]:.0f}")
            continue
        for cx, cy, rx, ry in ells:
            if ((ax - cx) / rx) ** 2 + ((ay - cy) / ry) ** 2 <= 1:
                mid = (top + bot) / 2
                for yy in (mid - 0.25 * (bot - top), mid + 0.25 * (bot - top)):
                    t = 1 - ((yy - cy) / ry) ** 2
                    half = rx * t ** 0.5 if t > 0 else 0
                    if x0 < cx - half + ELLIPSE_MARGIN or x1 > cx + half - ELLIPSE_MARGIN:
                        out.append(f"text {s!r} overflows its ellipse at ({cx:.0f}, {cy:.0f})")
                        break
                break
    for r in rects + [f + (0.0,) for f in frames]:
        if r[0] < -SLACK or r[1] < -SLACK or r[2] > W + SLACK or r[3] > H + SLACK:
            out.append(f"box at x {r[0]:.0f}..{r[2]:.0f}, y {r[1]:.0f}..{r[3]:.0f} runs off the canvas")
            continue
        if r[4] == 0.0:
            continue  # a frame is checked against the canvas only
        cx, cy = (r[0] + r[2]) / 2, (r[1] + r[3]) / 2
        outer = [o for o in rects if o is not r and o[0] <= cx <= o[2] and o[1] <= cy <= o[3]
                 and (o[2] - o[0]) * (o[3] - o[1]) > (r[2] - r[0]) * (r[3] - r[1])]
        if outer:
            o = min(outer, key=lambda o: (o[2] - o[0]) * (o[3] - o[1]))
            if r[0] < o[0] - SLACK or r[1] < o[1] - SLACK or r[2] > o[2] + SLACK or r[3] > o[3] + SLACK:
                out.append(f"box at x {r[0]:.0f}..{r[2]:.0f} crosses the edge of the frame at x {o[0]:.0f}..{o[2]:.0f}")
    for cx, cy, rx, ry in ells:
        if cx - rx < -SLACK or cx + rx > W + SLACK or cy - ry < -SLACK or cy + ry > H + SLACK:
            out.append(f"ellipse at ({cx:.0f}, {cy:.0f}) runs off the canvas")
    return list(dict.fromkeys(out))
