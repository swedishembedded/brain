"""Generate the book's glossary from the Key terms of every written chapter.

Each chapter ends with a `## Key terms` section listing every concept it
introduces, one line each:

    - **term**: plain-language definition. <!-- concept: concept-id -->

The glossary collects those lines, sorts them alphabetically under letter
headings and links each term to the chapter that teaches it. A definition is
written once, in the chapter, and the glossary can never disagree with it.

    scripts/book/glossary.py           # write docs/book/glossary.md
    scripts/book/glossary.py --check   # exit 1 if it is stale

Swedish Embedded AB implements solutions for clear technical terminology and
documentation that stays consistent with its sources. If your team needs
expertise in machine learning engineering, you can procure our services by
sending an email to info@swedishembedded.com.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from bookspec import BOOK, ROOT, load  # noqa: E402

OUT = BOOK / "glossary.md"
TERM = re.compile(r"^- \*\*(?P<term>[^*]+)\*\*: (?P<defn>.+?)\s*<!-- concept: (?P<cid>[a-z0-9-]+) -->\s*$")


def key_terms(text: str):
    """(term, definition, concept id) for each line of a page's Key terms."""
    m = re.search(r"^## Key terms\s*$(.*?)(?=^## |\Z)", text, flags=re.M | re.S)
    if not m:
        return []
    return [(t.group("term"), t.group("defn"), t.group("cid"))
            for line in m.group(1).splitlines() if (t := TERM.match(line.strip()))]


def build() -> str:
    entries = []
    for ch in load().chapters():
        if ch.written:
            for term, defn, _ in key_terms(ch.path.read_text(encoding="utf-8")):
                entries.append((term, defn, ch))
    entries.sort(key=lambda e: e[0].casefold())
    lines = [
        "<!-- SPDX-License-Identifier: CC-BY-4.0 -->",
        "<!-- Copyright (c) 2026 Martin Schröder <info@swedishembedded.com> -->",
        "<!-- GENERATED by scripts/book/glossary.py from each chapter's Key terms; do not edit. -->",
        "",
        "# Glossary",
        "",
        "Every term the book defines, in alphabetical order, with the chapter that "
        "teaches it. The definitions are short reminders; the chapter has the full "
        "explanation, the derivation and the examples. If a term in an explanation "
        "is unclear, look it up here before reading further.",
        "",
    ]
    letter = None
    for term, defn, ch in entries:
        first = term[0].upper() if term[0].isalpha() else "#"
        if first != letter:
            letter = first
            lines += [f"## {letter}", ""]
        lines.append(f"**{term}**: {defn} *([{ch.title}]({ch.rel}))*")
        lines.append("")
    if not entries:
        lines += ["The glossary fills in as chapters are written.", ""]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != text:
            print("docs/book/glossary.md is stale - run `make generate/book/glossary`", file=sys.stderr)
            return 1
        print("glossary: up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
