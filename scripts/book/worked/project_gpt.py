GC_STEP = 1e-5
GC_COORDS = 60
NAME_GC = "project_gpt.gradcheck"


@lru_cache(maxsize=None)
def gradient_results():
    cfg, d = config(), data()
    p = init_params()
    row = d["train"]["rows"][order()[0][0]]
    rows = [row]
    _, ana = tg.batch_loss(p, rows, cfg, "causal", grad=True)
    ts, names = tg.tensors(p), tg.tensor_names(cfg)
    g = bookrng.generator(NAME_GC)
    out = []
    for _ in range(GC_COORDS):
        k = g.integer(len(ts))
        r = g.integer(len(ts[k]))
        c = g.integer(len(ts[k][r]))
        keep = ts[k][r][c]
        ts[k][r][c] = keep + GC_STEP
        hi = tg.batch_loss(p, rows, cfg, "causal")[0]
        ts[k][r][c] = keep - GC_STEP
        lo = tg.batch_loss(p, rows, cfg, "causal")[0]
        ts[k][r][c] = keep
        num = (hi - lo) / (2 * GC_STEP)
        out.append((k, names[k], r, c, ana[k][r][c], num))
    return out, order()[0][0]


def gradient_check():
    out, row_id = gradient_results()
    groups = {}
    for k, name, r, c, a, n in out:
        label = tg._group_of(name)
        e = groups.setdefault(label, [0, 0.0, 0.0])
        e[0] += 1
        e[1] = max(e[1], abs(a))
        e[2] = max(e[2], abs(a - n))
    rows = []
    for label, _ in tg.GROUPS:
        if label in groups:
            n, big, err = groups[label]
            rows.append((label, n, _sci(big, 1), "below " + _below(max(err, 1e-30))))
    worst = max(abs(a - n) for _, _, _, _, a, n in out)
    scale = max(abs(a) for _, _, _, _, a, _ in out)
    first = out[0]
    assert worst < 1e-8
    return (f"The model of the forward check at its initialization, the loss of one training row (row {row_id}, the first row of the first batch) as the mean "
            f"cross-entropy over its supervised positions. {GC_COORDS} coordinates, drawn from seed {_seed(NAME_GC)} (`{NAME_GC}`): for each, `integer(n)` for the "
            f"tensor index of the table of the forward check ($n$ = {len(tg.tensors(init_params()))}), "
            f"then `integer(rows)` and `integer(columns)` of that tensor. Numerical derivative: central difference with step {GC_STEP:g} in float64. "
            f"For example the first coordinate is tensor index {first[0]}, row {first[2]}, column {first[3]}: analytic {first[4]:.9f}, numeric {first[5]:.9f}. "
            f"Largest absolute difference over the {GC_COORDS} coordinates: {_sci(worst, 1)}, against a largest analytic gradient of {_sci(scale, 1)}; "
            f"criterion: below $10^{{-8}}$ on every coordinate (the last column shows the power of ten that the group stayed below in this run).\n\n"
            + _table(["parameters", "coordinates drawn", "largest |analytic|", "largest |analytic - numeric|"], rows))


# ------------------------------------------------------------------------------------------------ milestone 4: training, checkpoints, resume

CHECKPOINT_STEP = 150
SHOW_STEPS = (10, 20, 30, 50, 100, 150, 200, 250, 300)


def zero_moments(p):
    return [([[0.0] * len(r) for r in t], [[0.0] * len(r) for r in t]) for t in tg.tensors(p)]


def save_checkpoint(p, mom, step):
    """Bytes of a checkpoint: the number of applied optimizer steps as a little-endian uint64, then all parameters, then all first
    moments, then all second moments, each as binary64 little-endian in the order of the weight digest, row-major."""
    out = [struct.pack("<Q", step)]
    for part in (tg.tensors(p), [m for m, _ in mom], [v for _, v in mom]):
        for t in part:
            for r in t:
                out.append(struct.pack(f"<{len(r)}d", *r))
    return b"".join(out)


def load_checkpoint(raw, template):
    """(parameters, moments, step) from the bytes of `save_checkpoint`; `template` gives the shapes."""
    step = struct.unpack_from("<Q", raw, 0)[0]
    pos = 8

    def fill(tensors):
        nonlocal pos
        out = []
        for t in tensors:
            rows = []
            for r in t:
                rows.append(list(struct.unpack_from(f"<{len(r)}d", raw, pos)))
                pos += 8 * len(r)
            out.append(rows)
        return out

    ts = tg.tensors(template)
    p_flat, m_flat, v_flat = fill(ts), fill(ts), fill(ts)
    assert pos == len(raw)
    p = _like(template, p_flat)
    return p, list(zip(m_flat, v_flat)), step


def _like(template, flat):
    """Parameters shaped like `template` (the dict of `init_gpt`) from tensors in the order of `tg.tensors`."""
    p = {"E": flat[0], "P": flat[1], "blocks": [], "gf": flat[-1]}
    k = 2
    for _ in template["blocks"]:
        p["blocks"].append(dict(zip(tg.BLOCK_KEYS, flat[k:k + len(tg.BLOCK_KEYS)])))
        k += len(tg.BLOCK_KEYS)
    return p


def advance(p, mom, first, last, counter):
    """Optimizer steps `first` .. `last - 1` of the batch order. `counter` is the number of applied updates at step `first`: it
    sets the learning rate and Adam's bias correction. Returns [(batch loss, gradient norm, clipped?)]."""
    cfg, o, d = config(), TRAIN, data()
    lr_of = schedules.cosine(o["peak"], o["floor"], o["warmup"], o["steps"])
    ts, decay = tg.tensors(p), tg.decayed(cfg)
    log = []
    for k, step in enumerate(range(first, last)):
        rows = [d["train"]["rows"][i] for i in order()[step]]
        loss, grads = tg.batch_loss(p, rows, cfg, "causal", grad=True)
        norm = tg.global_norm(grads)
        scale = min(1.0, o["clip"] / (norm + 1e-6))
        tg.adamw_update(ts, grads, mom, counter + k + 1, lr_of(counter + k), scale, decay, o)
        log.append((loss, norm, scale < 1.0))
    return log


def run(job):
    """One training run. job = (kind, nudge or None, checkpoint bytes or None). kind 'train' trains steps 0 .. 299 from the initial weights
    with the first weight changed by `nudge`, evaluating the validation loss every 10 steps and keeping the checkpoint at step 150. kind
    'resume:<variant>' loads the checkpoint, applies the variant and trains steps 150 .. 299."""
    kind, nudge, ckpt = job
    cfg, o, d = config(), TRAIN, data()
    val_rows = d["val"]["rows"]
    out = {"kind": kind, "nudge": nudge, "val": {}, "train": [], "gnorm": [], "clipped": 0}
    if kind == "train":
        p = init_params()
        p["E"][0][0] += nudge
        mom = zero_moments(p)
        out["val"][0] = tg.mean_loss(p, val_rows, cfg)
        first, counter = 0, 0
    else:
        p, mom, step = load_checkpoint(ckpt, init_params())
        variant = kind.split(":")[1]
        if variant == "no-moments":
            mom = zero_moments(p)
        counter = 0 if variant == "no-counter" else step
        first = step
    for lo in range(first, o["steps"], EVAL_EVERY):
        hi = min(lo + EVAL_EVERY, o["steps"])
        log = advance(p, mom, lo, hi, counter + (lo - first))
        for loss, norm, clipped in log:
            out["train"].append(loss)
            out["gnorm"].append(norm)
            out["clipped"] += 1 if clipped else 0
        out["val"][hi] = tg.mean_loss(p, val_rows, cfg)
        if kind == "train" and hi == CHECKPOINT_STEP:
            out["ckpt"] = save_checkpoint(p, mom, hi)
    out["params"] = p
    out["final_bytes"] = save_checkpoint(p, mom, o["steps"])
    return out


@lru_cache(maxsize=None)
def results():
    """({nudge: run} for the base run and four nudged runs, {variant: resumed run}); at most four processes at a time."""
    jobs = [("train", n, None) for n in (0.0, *stable.NUDGES)]
    with get_context("fork").Pool(4) as pool:
        first = pool.map(run, jobs[:4], chunksize=1)
        ckpt = first[0]["ckpt"]
        rest = [jobs[4]] + [(f"resume:{v}", None, ckpt) for v in ("full", "no-moments", "no-counter")]
        second = pool.map(run, rest, chunksize=1)
    trains = {r["nudge"]: r for r in first + second[:1]}
    resumed = {r["kind"].split(":")[1]: r for r in second[1:]}
    return trains, resumed


