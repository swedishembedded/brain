"""Worked examples for the Volume V project "Your Own Small Language Model": raw text to a trained GPT and a cache that provably
matches uncached generation.

Plain Python 3 on floats (IEEE double precision), standard library only, written from the project's own description. The libraries
of the earlier chapters are imported, never copied: the pre-tokenizer and byte-pair merges of Chapter 2 (`tokenization`) behind the
compact-vocabulary tokenizer of Chapter 10 (`training_gpt.Tokenizer`), the packing, the GPT with its forward and backward pass, the
AdamW step and the batch order of Chapter 10 (`training_gpt`, whose block is the one of Chapter 9, `transformer_block`), the rate
curve of Volume III (`schedules`), the sampling rules of Chapter 11 (`decoding`), the incremental forward pass of Chapter 12
(`kv_cache`) and the model device of Volume IV (`roofline`). What this module writes is what makes them one program:

* a corpus generated by a stated rule from a printed seed, split by document, and the checks of milestones 1 and 2 (digests of the
  merge list and of the first batch);
* digests of the initial weights and of a forward pass, and a central-difference check of the gradient at sampled coordinates;
* the training loop with checkpoints serialized to bytes and an exact resume, repeated from four nudged starting points so that
  trained numbers are printed with the digits that survive (`stable.py`);
* seeded generation (greedy, temperature, top-k, top-p) with and without the cache, the cache-equivalence test over every split of
  a text with a tolerance counted from the shapes, and the position mutations the test must catch;
* the work of the model: FLOPs per token for training and decoding, cache bytes per token and the arithmetic intensity of decoding.

Every random quantity comes from the book's SplitMix64 (`bookrng.generator(name)`); each block prints its seeds. Sums of products are
plain left-to-right additions, the order a C loop would use, except where a block says it changes the order. A digest of real numbers
is SHA-256 over the numbers scaled by a stated power of ten and rounded to the nearest integer (ties away from zero), each as a
signed 64-bit integer in little-endian byte order: a library that rounds `exp` or `cos` differently in the last bit does not change it.

Swedish Embedded AB implements solutions for training and serving small language models that can be verified end to end. If your
team needs expertise in language-model pipelines, cache correctness and inference cost, you can procure our services by sending an
email to info@swedishembedded.com.
"""
