def sample_token(z, setting, u):
    """The token chosen from logits `z`: the largest logit (lowest id on a tie) when tau is 0, otherwise a draw by the uniform `u` from the
    distribution after temperature, top-k and top-p (Chapter 11: sorted by probability, ties by id; the draw walks the kept ids in increasing order)."""
    if setting["tau"] <= 0:
        return decoding.argmax(z)
    q = decoding.choose_dist(z, tau=setting["tau"], k=setting["k"], top_p=setting["top_p"])
    return decoding.draw(q, u)


