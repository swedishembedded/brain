MUTATIONS = (("correct: the cache length", lambda c, plen: c),
             ("one too small: the last position already in the cache", lambda c, plen: c - 1),
             ("one too large", lambda c, plen: c + 1),
             ("never advanced: the length of the prompt", lambda c, plen: plen),
             ("restarted: position 0, the row index inside the call", lambda c, plen: 0))


MUTATION_PROMPT = 4


def mutation_diffs(p, cfg, ids, fn):
    """Largest logit difference from the reference at each decode step when the fed token is given position `fn(c, prompt length)`."""
    plen = MUTATION_PROMPT
    full, _ = tg.forward(p, ids, cfg, tg.causal)
    cache = kv.Cache(cfg["L"])
    kv.extend(p, cfg, cache, ids[:plen], kv.Meter())
    diffs = []
    for i in range(plen, len(ids)):
        row = kv.extend(p, cfg, cache, [ids[i]], kv.Meter(), positions=[fn(cache.length(), plen)])
        diffs.append(max(abs(a - b) for a, b in zip(row, full[i])))
    return diffs


def mutation_verdicts(p, cfg, ids, fn):
    """('pass' or 'FAIL') for the first-step test, the all-steps test and the greedy-token test."""
    plen = MUTATION_PROMPT
    tol = logit_tolerance(cfg, _z_max(p, cfg, ids))
    diffs = mutation_diffs(p, cfg, ids, fn)
    n_new = len(ids) - plen
    ref, _ = kv.generate_naive(p, cfg, ids[:plen], n_new)
    toks, _ = kv.generate_cached(p, cfg, ids[:plen], n_new, positions_of=fn)
    ok = lambda b: "pass" if b else "FAIL"
    return (ok(diffs[0] <= tol), ok(max(diffs) <= tol), ok(toks == ref))


