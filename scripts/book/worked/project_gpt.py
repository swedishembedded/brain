def cache_and_intensity():
    cfg = config()
    s = shape_of(cfg)
    gpu, cpu = roofline.MACHINES["GPU"], roofline.MACHINES["CPU"]
    ridge_gpu, ridge_cpu = gpu[0] / gpu[1], cpu[0] / cpu[1]
    b = BYTES_F32
    per = [(label, w, kv.cache_bytes_per_token(s, w)) for label, w in (("binary64 (this module)", BYTES_F64), ("float32", BYTES_F32), ("bfloat16", BYTES_BF16))]
    rows = []
    for c in (1, 8, 16, 19):
        f, wb, cb = kv.decode_work(s, c, 1, b)
        i = f / (wb + cb)
        rows.append((c, _int(f), _int(wb), _int(cb), _fx(i, 4), _fx(i / ridge_gpu, 4), _fx(i / ridge_cpu, 4)))
    prefill = []
    for n in (4, 10, 20):
        f, wb, cb = kv.prefill_work(s, n, b)
        i = f / (wb + cb)
        prefill.append((n, _int(f), _int(wb), _int(cb), _fx(i, 3), _fx(i / ridge_gpu, 4)))
    f16, _, c16 = kv.decode_work(s, 16, 1, b)
    naive, cached = kv.generation_flops(s, 4, 16)
    return (f"Cache bytes per token = 2 (keys and values) x L x D x bytes per number = 2 x {cfg['L']} x {cfg['D']} x b:\n\n"
            + _table(["numbers stored as", "b", "cache bytes per token", f"cache bytes at T = {cfg['T']}"], [(a, w, c, _int(c * cfg['T'])) for a, w, c in per])
            + f"\n\nDecode arithmetic intensity, one sequence, numbers stored in float32 (b = 4): the FLOPs of the step over the bytes it must read, which are the weights "
            f"once (4 $N_{{\\mathrm{{p}}}}$ bytes; the embedding lookup reads one row and is left out) and the cache rows of the $c$ tokens before the new one. "
            f"The devices are the two illustrative ones of Volume IV (`roofline.MACHINES`): the GPU, whose ridge is the peak over the bandwidth, {ridge_gpu:g} FLOP per byte, and, "
            f"in the last column, the CPU, whose ridge is {ridge_cpu:g}. 'Attainable' is the intensity over the ridge, capped at 1.\n\n"
            + _table(["cache length c", "FLOPs", "weight bytes", "cache bytes read", "FLOP per byte", "attainable fraction, GPU", "attainable fraction, CPU"], rows)
            + f"\n\nPrefill of n tokens into an empty cache (the weights read once, the cache rows written):\n\n"
            + _table(["n", "FLOPs", "weight bytes", "cache bytes written", "FLOP per byte", "attainable fraction, GPU"], prefill)
            + f"\n\nWith many sequences sharing one read of the weights, the intensity at a cache length of 16 tends to the FLOPs of one step over its own cache bytes, "
            f"{_int(f16)} / {_int(c16)} = {_fx(f16 / c16, 2)} FLOP per byte, which is below both ridges: no batch size makes this model's decode step compute-bound. "
            f"Generating 16 tokens after a prompt of 4 takes {_int(naive)} FLOPs when every step recomputes the whole text and {_int(cached)} with the cache, a factor of {_fx(naive / cached, 2)}.")


