FOREST_NAME = "classical.forest"
FOREST_MAX = 100


def _bootstrap(xs, ys, rng):
    idx = [rng.integer(len(xs)) for _ in range(len(xs))]
    return [xs[i] for i in idx], [ys[i] for i in idx]


def _forest_tree(xs, ys, rng, random_features):
    bx, by = _bootstrap(xs, ys, rng)
    sampler = (lambda: [rng.integer(2)]) if random_features else None
    return _build_tree(bx, by, [0, 1, 2], _entropy_bits, None, 0, sampler)


def _vote(trees, x, classes=(0, 1, 2)):
    votes = [0] * len(classes)
    for t in trees:
        votes[_tree_predict(t, x)] += 1
    return votes


def _vote_class(votes):
    return votes.index(max(votes))


