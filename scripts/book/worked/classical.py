def _mean_vec(rows):
    n = len(rows)
    return [sum(r[j] for r in rows) / n for j in range(len(rows[0]))]


def _centre(rows):
    mu = _mean_vec(rows)
    return mu, [[v - m for v, m in zip(r, mu)] for r in rows]


def _cov(centred):
    """Covariance with divisor N (the mean squared deviation), so the total variance is the mean squared distance to the mean."""
    n, d = len(centred), len(centred[0])
    return [[sum(r[i] * r[j] for r in centred) / n for j in range(d)] for i in range(d)]


def _pca(rows):
    """(mean, eigenvalues descending, components as rows) of the covariance of `rows`."""
    mu, xc = _centre(rows)
    vals, vecs = _jacobi_eigen(_cov(xc))
    return mu, vals, vecs


def _vec(v, d=3):
    return "(" + ", ".join(f"{x:.{d}f}" for x in v) + ")"


TINY_PCA = [(2.0, 1.0), (4.0, 3.0), (6.0, 4.0), (8.0, 6.0)]


def pca_trace():
    rows = TINY_PCA
    n = len(rows)
    mu, xc = _centre(rows)
    c = _cov(xc)
    tr, det = c[0][0] + c[1][1], c[0][0] * c[1][1] - c[0][1] ** 2
    disc = math.sqrt(tr * tr / 4 - det)
    l1, l2 = tr / 2 + disc, tr / 2 - disc
    # eigenvector for l1 from (C - l1 I) v = 0: v proportional to (c01, l1 - c00)
    v1 = (c[0][1], l1 - c[0][0])
    nv = math.hypot(*v1)
    v1 = (v1[0] / nv, v1[1] / nv)
    v2 = (-v1[1], v1[0])
    scores = [x[0] * v1[0] + x[1] * v1[1] for x in xc]
    recon = [(mu[0] + s * v1[0], mu[1] + s * v1[1]) for s in scores]
    err = sum(_sqdist(r, q) for r, q in zip(rows, recon))
    vals, vecs = _jacobi_eigen(c)
    # the other route: eigenvalues of the 4 x 4 matrix Xc Xc^T (nonzero ones equal N times those of C)
    g = [[_dot(a, b) for b in xc] for a in xc]
    gv, _ = _jacobi_eigen(g)
    out = [
        "Four points (x1, x2); covariance with divisor N = 4; every eigenvector is signed so that its entry of largest magnitude is positive. "
        "An eigenvalue that is zero up to rounding error (magnitude below 0.00005) is printed as 0.0000, whatever its sign.",
        "",
        _table(["n", "x1", "x2", "x1 centred", "x2 centred", "score on direction 1", "reconstruction (rank 1)"],
               [(i + 1, f"{rows[i][0]:g}", f"{rows[i][1]:g}", f"{xc[i][0]:.2f}", f"{xc[i][1]:.2f}", f"{scores[i]:.4f}", _pt(recon[i], 4)) for i in range(n)], "rrrrrrl"),
        "",
        f"Average point {_pt(mu)}. Covariance (divisor N = 4): [[{c[0][0]:.4f}, {c[0][1]:.4f}], [{c[0][1]:.4f}, {c[1][1]:.4f}]], trace {tr:.4f}, determinant {det:.4f}.",
        f"Eigenvalues from the quadratic formula: {l1:.4f} and {l2:.4f}. First direction {_vec(v1, 4)} (angle {math.degrees(math.atan2(v1[1], v1[0])):.2f} degrees), second {_vec(v2, 4)}.",
        f"Jacobi eigenvalues of the same matrix: {vals[0]:.4f} and {vals[1]:.4f}. Explained variance of direction 1: {100 * l1 / (l1 + l2):.2f}%.",
        f"Sum of squared reconstruction errors of the four points: {err:.4f}; N times the discarded eigenvalue: {n * l2:.4f}.",
        f"Eigenvalues of the 4 x 4 matrix Xc Xc^T: {', '.join(f'{abs(x) if abs(x) < 5e-5 else x:.4f}' for x in gv)}; N times the eigenvalues of the covariance: {n * l1:.4f}, {n * l2:.4f}. "
        f"Singular values of Xc: {math.sqrt(max(gv[0], 0)):.4f}, {math.sqrt(max(gv[1], 0)):.4f}.",
    ]
    return "\n".join(out)


