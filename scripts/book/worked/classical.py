def _gnb_fit(tx, ty, cols):
    model = []
    for c in range(3):
        rows = [p for p, t in zip(tx, ty) if t == c]
        stats = []
        for j in cols:
            vals = [r[j] for r in rows]
            m = sum(vals) / len(vals)
            v = max(sum((a - m) ** 2 for a in vals) / len(vals), 1e-9)
            stats.append((m, v))
        model.append((len(rows) / len(tx), stats))
    return model


def _gnb_posterior(model, x, cols):
    logs = []
    for prior, stats in model:
        lp = math.log(prior)
        for j, (m, v) in zip(cols, stats):
            lp += -0.5 * math.log(2 * math.pi * v) - (x[j] - m) ** 2 / (2 * v)
        logs.append(lp)
    mx = max(logs)
    e = [math.exp(v - mx) for v in logs]
    return [v / sum(e) for v in e]


def _gnb_predict(model, xs, cols):
    return [(lambda p: p.index(max(p)))(_gnb_posterior(model, x, cols)) for x in xs]


