def _entropy_bits(counts):
    n = sum(counts)
    h = -sum((c / n) * math.log2(c / n) for c in counts if c > 0)
    return h if h > 0.0 else 0.0


def _gini(counts):
    n = sum(counts)
    return 1.0 - sum((c / n) ** 2 for c in counts)


def _counts(ys, classes):
    return [sum(1 for y in ys if y == c) for c in classes]


def _best_split(xs, ys, classes, impurity, features=None, min_gain=1e-12):
    """The (feature, threshold, gain) with the largest impurity decrease; thresholds are midpoints between consecutive
    distinct values of a feature; the lowest feature, then the lowest threshold, wins a tie. None if no gain exceeds min_gain."""
    n = len(ys)
    parent = impurity(_counts(ys, classes))
    best = None
    for f in (range(len(xs[0])) if features is None else features):
        vals = sorted({x[f] for x in xs})
        for a, b in zip(vals, vals[1:]):
            t = (a + b) / 2
            left = [y for x, y in zip(xs, ys) if x[f] <= t]
            right = [y for x, y in zip(xs, ys) if x[f] > t]
            g = parent - (len(left) * impurity(_counts(left, classes)) + len(right) * impurity(_counts(right, classes))) / n
            if g > min_gain and (best is None or g > best[2] + 1e-12):
                best = (f, t, g)
    return best


def _build_tree(xs, ys, classes, impurity=_entropy_bits, max_depth=None, depth=0, feature_sampler=None):
    """A node is a dict. Leaf: class, counts. Split: feature, threshold, gain, counts, left, right."""
    counts = _counts(ys, classes)
    node = {"counts": counts, "n": len(ys), "class": classes[counts.index(max(counts))], "impurity": impurity(counts)}
    if max(counts) == len(ys) or (max_depth is not None and depth >= max_depth):
        return node
    feats = feature_sampler() if feature_sampler else None
    sp = _best_split(xs, ys, classes, impurity, feats)
    if sp is None:
        return node
    f, t, g = sp
    li = [i for i, x in enumerate(xs) if x[f] <= t]
    ri = [i for i, x in enumerate(xs) if x[f] > t]
    node.update(feature=f, threshold=t, gain=g)
    node["left"] = _build_tree([xs[i] for i in li], [ys[i] for i in li], classes, impurity, max_depth, depth + 1, feature_sampler)
    node["right"] = _build_tree([xs[i] for i in ri], [ys[i] for i in ri], classes, impurity, max_depth, depth + 1, feature_sampler)
    return node


def _tree_predict(node, x):
    while "feature" in node:
        node = node["left"] if x[node["feature"]] <= node["threshold"] else node["right"]
    return node["class"]


def _leaves(node):
    return 1 if "feature" not in node else _leaves(node["left"]) + _leaves(node["right"])


def _depth(node):
    return 0 if "feature" not in node else 1 + max(_depth(node["left"]), _depth(node["right"]))


