def _word_counts(docs):
    return [sum(d.split().count(w) for d in docs) for w in VOCAB]


def _nb_log_scores(msg, smoothing):
    """Log of prior x product of word probabilities for each class; None when a probability is exactly zero."""
    counts = {"spam": _word_counts(SPAM), "ham": _word_counts(HAM)}
    docs = {"spam": len(SPAM), "ham": len(HAM)}
    out = {}
    for c in ("spam", "ham"):
        total = sum(counts[c])
        lp = math.log(docs[c] / (docs["spam"] + docs["ham"]))
        for w in msg.split():
            num = counts[c][VOCAB.index(w)] + smoothing
            den = total + smoothing * len(VOCAB)
            if num == 0:
                lp = None
                break
            lp += math.log(num / den)
        out[c] = lp
    return out


