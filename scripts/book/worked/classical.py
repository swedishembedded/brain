def _onehot(ys):
    return [[1.0 if y == c else 0.0 for c in range(3)] for y in ys]


def _krr_fit_predict(tx, ty, ex, gamma, lam):
    n = len(tx)
    k = [[_rbf(tx[i], tx[j], gamma) + (lam if i == j else 0.0) for j in range(n)] for i in range(n)]
    coef = _solve(k, _onehot(ty))
    out = []
    for x in ex:
        ks = [_rbf(t, x, gamma) for t in tx]
        sc = [sum(ks[i] * coef[i][c] for i in range(n)) for c in range(3)]
        out.append(sc.index(max(sc)))
    return out


def _ridge_fit_predict(tx, ty, ex, lam):
    """Linear ridge on one-hot targets with an unpenalised intercept: features (x1, x2) centred, targets centred."""
    mu = _mean_vec(tx)
    xc = [[a - m for a, m in zip(p, mu)] for p in tx]
    y1 = _onehot(ty)
    ym = _mean_vec(y1)
    a = [[sum(r[p] * r[q] for r in xc) + (lam if p == q else 0.0) for q in range(2)] for p in range(2)]
    b = [[sum(xc[i][p] * (y1[i][c] - ym[c]) for i in range(len(tx))) for c in range(3)] for p in range(2)]
    w = _solve(a, b)
    out = []
    for x in ex:
        sc = [ym[c] + sum((x[p] - mu[p]) * w[p][c] for p in range(2)) for c in range(3)]
        out.append(sc.index(max(sc)))
    return out


