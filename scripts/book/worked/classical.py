def _true_rule(xs):
    """The Bayes rule for the generating distributions: the class whose Gaussian density at the point is largest (equal priors)."""
    out = []
    for x in xs:
        best, best_ll = 0, -math.inf
        for c in range(3):
            s1, s2, deg = SHAPES[c]
            th = math.radians(deg)
            dx, dy = x[0] - CENTRES[c][0], x[1] - CENTRES[c][1]
            a = dx * math.cos(th) + dy * math.sin(th)        # coordinates along the class's own axes
            b = -dx * math.sin(th) + dy * math.cos(th)
            ll = -math.log(s1 * s2) - 0.5 * ((a / s1) ** 2 + (b / s2) ** 2)
            if ll > best_ll:
                best, best_ll = c, ll
        out.append(best)
    return out


