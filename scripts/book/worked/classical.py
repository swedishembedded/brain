# ---------------------------------------------------------------- helpers

def _table(headers, rows, align=None):
    align = align or ("l" + "r" * (len(headers) - 1))
    sep = ["---:" if a == "r" else "---" for a in align]
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(sep) + "|"]
    for r in rows:
        out.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(out)


def _seed_line(name):
    return f"Generator: the book's SplitMix64, seed 0x{bookrng.seed_of(name):016x} ({bookrng.seed_of(name)})."


def _pt(p, d=2):
    return "(" + ", ".join(f"{v:.{d}f}" for v in p) + ")"


def _pct(v):
    return f"{100.0 * v:.1f}%"


# --------------------------------------------------------- linear algebra

def _solve(a, b):
    """Gaussian elimination with partial pivoting; a is n x n, b a list of n numbers or of n rows."""
    n = len(a)
    multi = isinstance(b[0], (list, tuple))
    m = [list(a[i]) + (list(b[i]) if multi else [b[i]]) for i in range(n)]
    w = len(m[0])
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(m[r][c]))
        if abs(m[p][c]) < 1e-300:
            raise ValueError("singular")
        m[c], m[p] = m[p], m[c]
        for r in range(c + 1, n):
            f = m[r][c] / m[c][c]
            if f != 0.0:
                for j in range(c, w):
                    m[r][j] -= f * m[c][j]
    out = [[0.0] * (w - n) for _ in range(n)]
    for k in range(w - n):
        for i in range(n - 1, -1, -1):
            s = m[i][n + k] - sum(m[i][j] * out[j][k] for j in range(i + 1, n))
            out[i][k] = s / m[i][i]
    return out if multi else [r[0] for r in out]


def _jacobi_eigen(s, sweeps=60):
    """Eigenvalues (descending) and eigenvectors (as rows) of a symmetric matrix by cyclic Jacobi rotations.

    Each eigenvector is signed so that its entry of largest magnitude is positive."""
    n = len(s)
    a = [list(r) for r in s]
    v = [[1.0 if i == j else 0.0 for j in range(n)] for i in range(n)]
    scale = sum(a[i][j] ** 2 for i in range(n) for j in range(n))
    for _ in range(sweeps):
        off = sum(a[i][j] ** 2 for i in range(n) for j in range(n) if i != j)
        if off <= 1e-30 * scale:
            break
        for p in range(n - 1):
            for q in range(p + 1, n):
                if a[p][q] != 0.0:
                    theta = (a[q][q] - a[p][p]) / (2.0 * a[p][q])
                    t = (1.0 if theta >= 0 else -1.0) / (abs(theta) + math.sqrt(theta * theta + 1.0))
                    c = 1.0 / math.sqrt(t * t + 1.0)
                    sn = t * c
                    for k in range(n):          # A <- A J
                        akp, akq = a[k][p], a[k][q]
                        a[k][p], a[k][q] = c * akp - sn * akq, sn * akp + c * akq
                    for k in range(n):          # A <- J^T A
                        apk, aqk = a[p][k], a[q][k]
                        a[p][k], a[q][k] = c * apk - sn * aqk, sn * apk + c * aqk
                    for k in range(n):          # V <- V J
                        vkp, vkq = v[k][p], v[k][q]
                        v[k][p], v[k][q] = c * vkp - sn * vkq, sn * vkp + c * vkq
    order = sorted(range(n), key=lambda i: -a[i][i])
    vals = [a[i][i] for i in order]
    vecs = [[v[k][i] for k in range(n)] for i in order]
    for vec in vecs:
        j = max(range(n), key=lambda t: abs(vec[t]))
        if vec[j] < 0:
            for t in range(n):
                vec[t] = -vec[t]
    return vals, vecs


def _dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def _sqdist(a, b):
    return sum((x - y) ** 2 for x, y in zip(a, b))


# ------------------------------------------------------ the shared dataset

@lru_cache(maxsize=None)
def _dataset():
    """{'train': (X, y), 'val': ..., 'test': ...}: three classes, the book's generator, points rounded to 2 decimals."""
    rng = bookrng.generator(DATA_NAME)
    out = {}
    for split, n in (("train", N_TRAIN), ("val", N_VAL), ("test", N_TEST)):
        xs, ys = [], []
        for i in range(n):
            c = i % 3
            z1, z2 = rng.normal(), rng.normal()
            s1, s2, deg = SHAPES[c]
            a, b = s1 * z1, s2 * z2
            th = math.radians(deg)
            x1 = CENTRES[c][0] + a * math.cos(th) - b * math.sin(th)
            x2 = CENTRES[c][1] + a * math.sin(th) + b * math.cos(th)
            xs.append((round(x1, 2) + 0.0, round(x2, 2) + 0.0))   # + 0.0 turns -0.0 into 0.0
            ys.append(c)
        out[split] = (xs, ys)
    return out


def _acc(pred, y):
    return sum(1 for p, t in zip(pred, y) if p == t) / len(y)


# ======================================================== nearest neighbours

def _norm_dist(a, b, norm):
    if norm == 1:
        return sum(abs(x - y) for x, y in zip(a, b))
    if norm == 2:
        return math.sqrt(_sqdist(a, b))
    return max(abs(x - y) for x, y in zip(a, b))        # norm == "inf"


def _knn_predict(tx, ty, x, k, norm=2):
    """The k nearest rows by (distance, index); the majority label, a tie going to the smallest label."""
    ds = sorted((_norm_dist(p, x, norm), i) for i, p in enumerate(tx))
    votes = {}
    for _, i in ds[:k]:
        votes[ty[i]] = votes.get(ty[i], 0) + 1
    best = max(votes.values())
    return min(c for c, v in votes.items() if v == best)


def _knn_acc(tx, ty, ex, ey, k, norm=2):
    return _acc([_knn_predict(tx, ty, x, k, norm) for x in ex], ey)


def dataset_head():
    d = _dataset()
    tx, ty = d["train"]
    rows = [(i + 1, f"{tx[i][0]:.2f}", f"{tx[i][1]:.2f}", CLASS_NAMES[ty[i]]) for i in range(6)]
    cls = []
    for c in range(3):
        pts = [p for p, t in zip(tx, ty) if t == c]
        m = (sum(p[0] for p in pts) / len(pts), sum(p[1] for p in pts) / len(pts))
        cls.append((CLASS_NAMES[c], len(pts), _pt(CENTRES[c], 1), f"{SHAPES[c][0]}, {SHAPES[c][1]}, {SHAPES[c][2]:g} deg", _pt(m)))
    return (
        f"{_seed_line(DATA_NAME)} Three classes A, B, C. Each point is two draws, z1 = rng.normal() then z2 = rng.normal(); "
        "with the class's standard deviations (s1, s2) and angle (in degrees, converted to radians for cos and sin), a = s1 z1 and b = s2 z2, "
        "x1 = c1 + a cos(angle) - b sin(angle) and x2 = c2 + a sin(angle) + b cos(angle), rounded to 2 decimals. "
        f"Rows are drawn in order, the class cycling A, B, C, A, ...: first {N_TRAIN} training rows, then {N_VAL} validation rows, then {N_TEST} test rows, "
        "from one generator without reseeding.\n\n"
        + _table(["class", "training rows", "centre (c1, c2)", "s1, s2, angle", "average of training rows"], cls, "lrlll")
        + "\n\nThe first six training rows:\n\n" + _table(["n", "x1", "x2", "class"], rows, "lrrl")
    )


def knn_trace():
    pts = [("a", (3.0, 0.0), 0), ("b", (2.2, 2.2), 1), ("c", (-1.0, 3.5), 1), ("d", (-2.5, -1.0), 0), ("e", (1.0, -2.0), 1)]
    q = (0.0, 0.0)
    rows = []
    for name, p, c in pts:
        rows.append((name, _pt(p, 1), CLASS_NAMES[c], f"{_norm_dist(p, q, 1):.2f}", f"{_norm_dist(p, q, 2):.2f}", f"{_norm_dist(p, q, 'inf'):.2f}"))
    tx = [p for _, p, _ in pts]
    ty = [c for _, _, c in pts]
    res = []
    for norm, nm in ((1, "L1"), (2, "L2"), ("inf", "L-infinity")):
        order = sorted((_norm_dist(p, q, norm), n) for n, p, _ in pts)
        names = [n for _, n in order]
        row = [nm, ", ".join(names[:3])]
        for k in (1, 3):
            row.append(CLASS_NAMES[_knn_predict(tx, ty, q, k, norm)])
        res.append(tuple(row))
    return ("Five labelled points and the query q = (0, 0):\n\n"
            + _table(["point", "(x1, x2)", "class", "L1 distance", "L2 distance", "L-infinity distance"], rows, "llrrrr")
            + "\n\nThe neighbours in order of increasing distance (first three, nearest first) and the vote for k = 1 and k = 3:\n\n"
            + _table(["norm", "three nearest", "class for k = 1", "class for k = 3"], res, "llrr"))


KS = (1, 3, 5, 9, 15, 21, 31)


@lru_cache(maxsize=None)
def _knn_sweep():
    d = _dataset()
    tx, ty = d["train"]
    vx, vy = d["val"]
    rows = []
    for k in KS:
        tr = _acc([_knn_predict(tx, ty, x, k) for x in tx], ty)      # a training row is its own nearest neighbour
        va = _knn_acc(tx, ty, vx, vy, k)
        rows.append((k, tr, va))
    best = max(rows, key=lambda r: (round(r[2], 12), -r[0]))[0]       # highest validation accuracy, then the smaller k
    return rows, best


def knn_k_sweep():
    rows, best = _knn_sweep()
    out = [(k, _pct(tr), _pct(va), "best" if k == best else "") for k, tr, va in rows]
    return ("L2 distance, majority vote, a vote tie going to the smaller class label. Training accuracy counts each training row as its own nearest neighbour (distance 0). "
            "Validation: the 300 validation rows; the best k has the highest validation accuracy, the smaller k on a tie.\n\n"
            + _table(["k", "training accuracy", "validation accuracy", "chosen"], out, "rrrl"))


def knn_norms_and_test():
    d = _dataset()
    tx, ty = d["train"]
    vx, vy = d["val"]
    ex, ey = d["test"]
    _, kb = _knn_sweep()
    rows = []
    for norm, nm in ((1, "L1"), (2, "L2"), ("inf", "L-infinity")):
        rows.append((nm, _pct(_knn_acc(tx, ty, vx, vy, kb, norm))))
    test = _knn_acc(tx, ty, ex, ey, kb)
    return (f"Validation accuracy at k = {kb} for three distances:\n\n" + _table(["distance", "validation accuracy"], rows, "lr")
            + f"\n\nTest accuracy of k = {kb} with L2 (600 test rows, looked at once): {_pct(test)}.")


SCALE_NAME = "classical.knn_extra_feature"


def knn_irrelevant_feature():
    d = _dataset()
    tx, ty = d["train"]
    vx, vy = d["val"]
    rng = bookrng.generator(SCALE_NAME)
    u_train = [rng.uniform() for _ in tx]
    u_val = [rng.uniform() for _ in vx]
    rows = []
    for s in (0.0, 1.0, 10.0, 100.0):
        a = [p + (s * u,) for p, u in zip(tx, u_train)]
        b = [p + (s * u,) for p, u in zip(vx, u_val)]
        raw = _knn_acc(a, ty, b, vy, 5)
        cols = list(zip(*a))
        mu = [sum(c) / len(c) for c in cols]
        sd = [math.sqrt(sum((v - m) ** 2 for v in c) / len(c)) or 1.0 for c, m in zip(cols, mu)]
        za = [tuple((v - m) / s_ for v, m, s_ in zip(p, mu, sd)) for p in a]
        zb = [tuple((v - m) / s_ for v, m, s_ in zip(p, mu, sd)) for p in b]
        rows.append((f"{s:g}", _pct(raw), _pct(_knn_acc(za, ty, zb, vy, 5)) if s > 0 else "-"))
    return (f"{_seed_line(SCALE_NAME)} A third feature x3 = s u is added to every row, with u = rng.uniform(): first one draw for each of the 90 training rows in order, "
            "then one for each of the 300 validation rows in order. k = 5, L2 distance. Standardised: each of the three features minus its training average and divided by its training standard deviation (divisor N).\n\n"
            + _table(["scale s of the useless feature", "validation accuracy, raw", "validation accuracy, standardised"], rows, "rrr"))


CONC_NAME = "classical.concentration"


def distance_concentration():
    rng = bookrng.generator(CONC_NAME)
    rows = []
    for dim in (2, 10, 100, 1000):
        pts = [[rng.uniform() for _ in range(dim)] for _ in range(200)]
        q = pts[0]
        ds = [math.sqrt(_sqdist(q, p)) for p in pts[1:]]
        mean = sum(ds) / len(ds)
        sd = math.sqrt(sum((v - mean) ** 2 for v in ds) / len(ds))
        rows.append((dim, f"{mean:.3f}", f"{sd / mean:.3f}", f"{(max(ds) - min(ds)) / min(ds):.3f}", f"{min(ds) / mean:.3f}"))
    return (f"{_seed_line(CONC_NAME)} For each dimension d in turn (2, 10, 100, 1000), 200 points with d coordinates drawn by rng.uniform(), point after point, coordinate after coordinate, "
            "from one generator. The first point is the query; the L2 distances to the other 199 are summarised (standard deviation with divisor 199).\n\n"
            + _table(["d", "mean distance", "std / mean", "(max - min) / min", "nearest / mean"], rows))


# ================================================================= k-means

def _assign(points, centres):
    """Index of the nearest centre for each point (squared L2), a tie going to the lowest index."""
    out = []
    for p in points:
        ds = [_sqdist(p, c) for c in centres]
        out.append(ds.index(min(ds)))
    return out


def _objective(points, centres, assign):
    return sum(_sqdist(p, centres[a]) for p, a in zip(points, assign))


def _update(points, centres, assign):
    """Each centre moves to the mean of its points; a centre with no points stays."""
    new = []
    for j, c in enumerate(centres):
        mine = [p for p, a in zip(points, assign) if a == j]
        new.append(tuple(sum(p[i] for p in mine) / len(mine) for i in range(len(c))) if mine else tuple(c))
    return new


def _lloyd(points, centres, max_rounds=100):
    """Lloyd's algorithm. Each round is (centres used, assignment, J after the assignment, J after the update);
    the last round is the one whose assignment equals the previous round's, and it leaves the centres where they are."""
    centres = [tuple(c) for c in centres]
    rounds = []
    prev = None
    for _ in range(max_rounds):
        assign = _assign(points, centres)
        j_assign = _objective(points, centres, assign)
        if assign == prev:
            rounds.append((centres, assign, j_assign, j_assign))
            break
        new = _update(points, centres, assign)
        rounds.append((centres, assign, j_assign, _objective(points, new, assign)))
        centres, prev = new, assign
    return rounds, centres, assign


def _kmeans_final(points, centres):
    rounds, centres, assign = _lloyd(points, centres)
    return _objective(points, centres, assign), centres, assign, rounds


def _random_init(points, k, rng):
    """k distinct rows: shuffle the row numbers 0 .. N-1 with the book's shuffle and take the first k."""
    idx = list(range(len(points)))
    rng.shuffle(idx)
    return [points[i] for i in idx[:k]]


def _kmeanspp_init(points, k, rng):
    """k-means++: the first centre is row rng.integer(N); each next one is drawn with probability proportional to
    the squared distance to the nearest centre chosen so far (one rng.uniform() per centre)."""
    centres = [points[rng.integer(len(points))]]
    while len(centres) < k:
        near = [min(_sqdist(p, c) for c in centres) for p in points]
        pick = rng.uniform() * sum(near)
        chosen = len(points) - 1
        for i, v in enumerate(near):
            pick -= v
            if pick <= 0.0:
                chosen = i
                break
        centres.append(points[chosen])
    return centres


def kmeans_trace():
    pts = [(1.0, 1.0), (1.5, 2.0), (3.0, 4.0), (5.0, 7.0), (3.5, 5.0), (4.5, 5.0)]
    start = [(1.0, 1.0), (1.5, 2.0)]
    rounds, final, assign = _lloyd(pts, start)
    rows = []
    for r, (cs, a, ja, ju) in enumerate(rounds, 1):
        rows.append((r, f"{_pt(cs[0])} {_pt(cs[1])}", "".join("12"[i] for i in a), f"{ja:.3f}", f"{ju:.3f}"))
    chain = []
    for (cs, a, ja, ju), nxt in zip(rounds, rounds[1:] + [None]):
        chain.append(ja)
        chain.append(ju)
    mono = all(x >= y - 1e-12 for x, y in zip(chain, chain[1:]))
    return ("Six points " + ", ".join(_pt(p, 1) for p in pts) + "; starting centres " + " and ".join(_pt(c, 1) for c in start) + ". "
            "A tie goes to the lower centre; the loop stops when an assignment equals the previous one.\n\n"
            + _table(["round", "centres used by the assignment", "assignment of the six points", "J after assigning", "J after moving the centres"], rows, "rlrrr")
            + f"\n\nFinal centres {_pt(final[0])} and {_pt(final[1])}, final J {_objective(pts, final, assign):.3f}. "
            + f"The sequence J(assign 1), J(move 1), J(assign 2), ... never increases: {'yes' if mono else 'NO'}.")


INIT_NAME = "classical.kmeans_init"
K_MEANS_K = 3
RESTARTS = 100
REACH_TOL = 0.005      # a run "reaches the lowest" when its J is below the lowest J of that k plus this


def _train_points():
    return _dataset()["train"][0]


@lru_cache(maxsize=None)
def _restart_runs():
    """RESTARTS random starts then RESTARTS k-means++ starts on the 90 training rows, for k = 3 and then k = 6, from one generator."""
    pts = _train_points()
    rng = bookrng.generator(INIT_NAME)
    runs = {}
    for k in (3, 6):
        for name, init in (("random rows", _random_init), ("k-means++", _kmeanspp_init)):
            runs[(k, name)] = [_kmeans_final(pts, init(pts, k, rng)) for _ in range(RESTARTS)]
    return runs


def kmeans_restarts():
    runs = _restart_runs()
    rows = []
    for k in (3, 6):
        best = min(r[0] for (kk, _), rs in runs.items() if kk == k for r in rs)
        for (kk, name), rs in runs.items():
            if kk != k:
                continue
            js = sorted(r[0] for r in rs)
            hits = sum(1 for j in js if j < best + REACH_TOL)
            rounds_mean = sum(len(r[3]) for r in rs) / len(rs)
            median = (js[len(js) // 2 - 1] + js[len(js) // 2]) / 2        # an even count: the average of the two middle values
            rows.append((k, name, f"{js[0]:.2f}", f"{median:.2f}", f"{js[-1]:.2f}", f"{sum(js) / len(js):.2f}", f"{hits} of {RESTARTS}", f"{rounds_mean:.1f}"))
    return (f"{_seed_line(INIT_NAME)} Points: the 90 training rows without their labels. In order, from one generator: {RESTARTS} random starts and {RESTARTS} k-means++ starts for k = 3, then the same for k = 6. "
            "A random start shuffles the numbers 0 .. 89 with `shuffle` and takes the first k rows as centres. "
            "A k-means++ start draws the first centre as row `rng.integer(90)`, then each further centre with one `rng.uniform()`: "
            "target = uniform x (sum of D2), walk the rows in order subtracting each D2(row) from target, and take the first row at which target <= 0 (D2 = squared distance from the row to the nearest centre chosen so far). "
            "Lloyd's rounds follow until the assignment repeats; the rounds counted include the last, confirming one, and 'mean rounds' is their average over the 100 runs of the row. J is the sum of squared distances to the assigned centre. "
            "'Lowest' is the lowest J found by any of the 200 runs at that k (both starts together); a run 'reaches the lowest' when its J is less than 0.005 above that value. "
            "'Median J' of the 100 runs of a row is the average of the 50th and 51st smallest values (the median of the book's pseudocode page). Mean J is the average of the 100 values.\n\n"
            + _table(["k", "start", "lowest J", "median J", "highest J", "mean J", "runs reaching the lowest", "mean rounds"], rows, "rlrrrrrr"))


def _first_runs():
    """One poor start (the three rows with the smallest x1) and the first k-means++ start of the restart experiment."""
    pts = _train_points()
    order = sorted(range(len(pts)), key=lambda i: (pts[i][0], i))
    poor = [pts[i] for i in order[:3]]
    rng = bookrng.generator(INIT_NAME + ".single")
    plus = _kmeanspp_init(pts, K_MEANS_K, rng)
    return _kmeans_final(pts, poor), _kmeans_final(pts, plus), poor, plus


def kmeans_objective_by_round():
    (jp, cp, ap, rp), (jq, cq, aq, rq), poor, plus = _first_runs()
    n = max(len(rp), len(rq))
    rows = []
    for r in range(n):
        a = f"{rp[r][2]:.2f}" if r < len(rp) else "(stopped)"
        b = f"{rp[r][3]:.2f}" if r < len(rp) else ""
        c = f"{rq[r][2]:.2f}" if r < len(rq) else "(stopped)"
        d = f"{rq[r][3]:.2f}" if r < len(rq) else ""
        rows.append((r + 1, a, b, c, d))
    return ("Poor start: the three training rows with the smallest x1, " + ", ".join(_pt(p) for p in poor) + ". "
            f"k-means++ start: generator seed 0x{bookrng.seed_of(INIT_NAME + '.single'):016x} ({bookrng.seed_of(INIT_NAME + '.single')}); one draw `rng.integer(90)`, then two draws of `rng.uniform()`; the centres chosen are "
            + ", ".join(_pt(p) for p in plus) + ". The rounds are Lloyd's, the last one being the round whose assignment equals the previous round's.\n\n"
            + _table(["round", "poor start: J after assigning", "J after moving", "k-means++ start: J after assigning", "J after moving"], rows)
            + f"\n\nFinal J: poor start {jp:.2f}, k-means++ start {jq:.2f}.")


