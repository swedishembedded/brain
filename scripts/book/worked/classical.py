def _psi2(x):
    """The degree-2 polynomial feature map of a point of the plane: 6 features, with the sqrt(2) factors that make psi(x).psi(y) = (x.y + 1)^2."""
    r2 = math.sqrt(2.0)
    return [1.0, r2 * x[0], r2 * x[1], x[0] ** 2, r2 * x[0] * x[1], x[1] ** 2]


def _poly2(x, y):
    return (_dot(x, y) + 1.0) ** 2


def _rbf(x, y, gamma):
    return math.exp(-gamma * _sqdist(x, y))


