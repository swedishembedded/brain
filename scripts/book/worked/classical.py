def _best_stump(xs, ys, w):
    """Stump: predicts s when x <= t, else -s. Lowest weighted error; ties to the lower t, then s = +1 first."""
    best = None
    for t in [x + 0.5 for x in xs[:-1]]:
        for s in (1, -1):
            err = sum(wi for x, y, wi in zip(xs, ys, w) if (s if x <= t else -s) != y)
            if best is None or err < best[0] - 1e-12:
                best = (err, t, s)
    return best


def adaboost_rounds():
    xs, ys = ADA_X, ADA_Y
    n = len(xs)
    w = [1.0 / n] * n
    stumps = []
    parts = []
    summary = []
    for m in range(1, 7):
        err, t, s = _best_stump(xs, ys, w)
        alpha = 0.5 * math.log((1 - err) / err)
        h = [s if x <= t else -s for x in xs]
        new = [wi * math.exp(-alpha * y * hi) for wi, y, hi in zip(w, ys, h)]
        z = sum(new)
        new = [v / z for v in new]
        stumps.append((alpha, t, s))
        score = [sum(a * (ss if x <= tt else -ss) for a, tt, ss in stumps) for x in xs]
        pred = [1 if v >= 0 else -1 for v in score]
        wrong = sum(1 for p, y in zip(pred, ys) if p != y)
        summary.append((m, f"x <= {t:g} gives {s:+d}, else {-s:+d}", f"{err:.4f}", f"{alpha:.4f}", f"{z:.4f}", wrong))
        if m <= 3:
            parts.append((m, w, h, new))
        w = new
    rows = []
    for i in range(n):
        row = [ADA_X[i], f"{ADA_Y[i]:+d}"]
        for m, ww, h, new in parts:
            row += [f"{ww[i]:.4f}", f"{h[i]:+d}", f"{new[i]:.4f}"]
        rows.append(tuple(row))
    heads = ["x", "y"]
    for m, *_ in parts:
        heads += [f"q before round {m}", f"h{m}(x)", f"q after round {m}"]
    return ("Ten points with x = 0 .. 9 and labels y = +, +, +, -, -, -, +, +, +, -. Initial weights q = 1/10 each. A stump predicts s when x <= t and -s otherwise, for t at the half-integers 0.5 .. 8.5 and s = +1 or -1; "
            "the best stump has the smallest weighted error (the lowest t, then s = +1, on a tie). Its vote weight is v = 0.5 ln((1 - err)/err); the new weight is the old one times exp(-v y h(x)), divided by the sum Z of these products. "
            "The combined classifier is the sign of the sum of v h over the rounds so far (sign(0) = +1). Six rounds are run; the first three are shown in the weight table.\n\n"
            + _table(heads, rows, "r" * len(heads))
            + "\n\nThe rounds, and the number of training points the combined classifier gets wrong after each:\n\n"
            + _table(["round", "stump", "weighted error", "v", "Z", "errors of the sum so far"], summary, "rlrrrr"))


