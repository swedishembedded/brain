# ------------------------------------------------- decision regions (figures)

def _region_runs(predict, xlim, ylim, n):
    """Class of the centre of each cell of an n x n grid; returns, per row from the bottom, the runs (start, end, class) of equal class."""
    xs = [xlim[0] + (i + 0.5) * (xlim[1] - xlim[0]) / n for i in range(n)]
    ys = [ylim[0] + (j + 0.5) * (ylim[1] - ylim[0]) / n for j in range(n)]
    classes = predict([(x, y) for y in ys for x in xs])
    rows = []
    for j in range(n):
        row = classes[j * n:(j + 1) * n]
        runs, start = [], 0
        for i in range(1, n + 1):
            if i == n or row[i] != row[start]:
                runs.append((start, i, row[start]))
                start = i
        rows.append(runs)
    return rows


REGION_FILLS = ("#dce8f5", "#f8e3d6", "#d9eee2")


def paint_regions(plot, predict, n=60):
    """Shade the plot area by the predicted class: one rectangle per run of equal class in each row of an n x n grid of cells."""
    (x0, x1), (y0, y1) = plot.xlim, plot.ylim
    rows = _region_runs(predict, plot.xlim, plot.ylim, n)
    cw, ch = (x1 - x0) / n, (y1 - y0) / n
    items = []
    for j, runs in enumerate(rows):
        ya, yb = y0 + j * ch, y0 + (j + 1) * ch
        top, bottom = plot.y(yb), plot.y(ya)
        for a, b, c in runs:
            left, right = plot.x(x0 + a * cw), plot.x(x0 + b * cw)
            items.append(f'<rect x="{left:.1f}" y="{top:.1f}" width="{right - left + 0.3:.1f}" height="{bottom - top + 0.3:.1f}" '
                         f'fill="{REGION_FILLS[c]}" stroke="none"/>')
    plot.items[:0] = items
