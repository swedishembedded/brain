"""Regenerate `.agents/roadmap/index.md` from the ledgers beside it.

A roadmap is the one place a model's or a workstream's status, open work and
measured numbers live; nothing else in the repository restates them. The index
is how a reader finds the right ledger without opening the directory, and it is
generated, so it cannot drift from the files the way a hand-maintained list
does.

A ledger is any `.agents/roadmap/<name>.md` whose first `# ` heading is its
title, followed by a one-line `Scope: <sentence>` naming what the ledger covers
(crates, sample or workstream). The scope is required: it is what lets a reader
route by subject, and a heuristic "first sentence" picks up whatever paragraph
happens to come first. A trailing " - roadmap" on the title is dropped.

    scripts/build/gen-roadmap-index.py           # write the index
    scripts/build/gen-roadmap-index.py --check   # fail if it would change

Swedish Embedded AB implements solutions for keeping engineering status in one
place, out of the guides that route people to it, for its clients. If your team
needs expertise in documentation that cannot drift from the work it describes,
you can procure our services by sending an email to info@swedishembedded.com.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ROADMAP = ROOT / ".agents" / "roadmap"
INDEX = ROADMAP / "index.md"

HEADER = """<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- Copyright (c) 2026 Martin Schröder <info@swedishembedded.com> -->
<!-- GENERATED by scripts/build/gen-roadmap-index.py - edit the ledgers, not this file. -->

# Roadmap index - where status and open work live

One ledger per model or cross-cutting workstream. A ledger holds what is done,
what is open, and the measured numbers behind both. Status is written here and
nowhere else: `AGENTS.md`, `.agents/rules/` and `docs/` point at a ledger
rather than restating it.

Add a ledger as `.agents/roadmap/<name>.md` with its title as the first `# `
heading and a `Scope: <one sentence>` line under it, then run `make generate/roadmap/index`. `make test/full` runs
`check/generated/roadmap-index`, which fails when this index has drifted.

## Ledgers

"""

SUFFIX = re.compile(r"\s+-\s+roadmap$")
SCOPE = "Scope: "


def entries():
    out = []
    for path in sorted(ROADMAP.glob("*.md")):
        if path.name == "index.md":
            continue
        lines = path.read_text().splitlines()
        at = next((i for i, line in enumerate(lines) if line.startswith("# ")), None)
        if at is None:
            sys.exit(f"{path.name}: no `# ` heading - every ledger states its own title")
        title = SUFFIX.sub("", lines[at][2:].strip())
        # A title may wrap onto further `# ` lines; the scope is the first
        # non-blank line after it.
        rest = [line for line in lines[at + 1:] if line.strip() and not line.startswith("# ")]
        scope = rest[0][len(SCOPE):].strip() if rest and rest[0].startswith(SCOPE) else None
        if not scope:
            sys.exit(f"{path.name}: no `{SCOPE}<sentence>` line under the title - say what this ledger covers")
        out.append((path.stem, title, scope, path.name))
    return out


def render(rows):
    body = ["| ledger | title | scope |", "|---|---|---|"]
    for stem, title, about, name in rows:
        # Text may carry inline code; a pipe inside it would split the row.
        cells = [c.replace("|", "\\|") for c in (title, about)]
        body.append(f"| [`{stem}`]({name}) | {cells[0]} | {cells[1]} |")
    return HEADER + "\n".join(body) + "\n"


def main():
    rows = entries()
    want = render(rows)
    if "--check" in sys.argv:
        have = INDEX.read_text() if INDEX.exists() else ""
        if have != want:
            sys.exit("roadmap index is out of date - run `make generate/roadmap/index` and commit the result")
        print(f"roadmap index up to date ({len(rows)} ledgers)")
        return
    INDEX.write_text(want)
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(rows)} ledgers)")


if __name__ == "__main__":
    main()
