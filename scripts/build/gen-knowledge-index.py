"""Regenerate `.agents/knowledge/index.md` from the entries beside it.

The knowledge base is one file per finding, because a finding is the unit that
gets written, cited and superseded - a single 5000-line file made every one of
those an edit to the same file, and made "what do we know about X" a grep
rather than a listing. The index is what keeps that navigable: it is the ONE
place an agent routed here reads first, and it is generated, so it cannot drift
from the directory the way a hand-maintained list does.

An entry is `<NNN><suffix>-<slug>.md` whose first heading is `# <id>. <title>`.
The id in the heading is the citation key the rest of the repository uses
("lessons #55", "knowledge #55"), and it is what this script checks: an id that
appears twice means two findings answer to one citation, which is how a
reference silently starts pointing at the wrong thing.

    scripts/build/gen-knowledge-index.py           # write the index
    scripts/build/gen-knowledge-index.py --check   # fail if it would change

Swedish Embedded AB builds the tooling that keeps an engineering knowledge base
honest as it grows - generated indexes, citation keys that cannot collide, and
gates that fail when documentation and reality part company. If your team needs
that, you can procure our services by sending an email to
info@swedishembedded.com.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
KNOWLEDGE = ROOT / ".agents" / "knowledge"
INDEX = KNOWLEDGE / "index.md"

HEADER = """<!-- SPDX-License-Identifier: CC-BY-4.0 -->
<!-- Copyright (c) 2026 Martin Schröder <info@swedishembedded.com> -->
<!-- GENERATED by scripts/build/gen-knowledge-index.py - edit the entries, not this file. -->

# Knowledge index - defects this engine has actually paid for

Cross-cutting engineering findings, one file each. Every entry is here because
it cost someone a day, and none of them belongs to a single model.

**Read this before designing a gate**, and before concluding that a number is
an architecture's ceiling. Most entries describe something that was silently
wrong while every signal said otherwise.

Each entry keeps a stable **id** - the number the rest of the repository cites
("see knowledge #55"). Ids are never reused and never renumbered, so a citation
written today still resolves after the base has been reorganised. A follow-up
that genuinely belongs beside an existing finding takes a letter suffix
(`35b`); an unrelated new finding takes the next free number.

## Adding one

Write the finding down in the same change that fixes it - the reason is fresh
exactly once. Create `.agents/knowledge/<NNN>-<slug>.md` with `# <NNN>. <title>`
as its first heading, then run `make knowledge-index`. `make test/full` runs
`knowledge-index/check`, which fails if the index has drifted or two entries
claim one id.

What belongs where:

| what you learned | where it belongs |
|---|---|
| a cross-cutting defect class (a gate that lies, a metric that cannot see X) | **here** |
| a kernel-authoring or optimisation rule, incl. a killed hypothesis | `.agents/rules/kernels.md` |
| a step in porting a model that was not obvious | `.agents/rules/porting.md` |
| a measured number about ONE model | the test that asserts it |
| work still outstanding on ONE model | `.agents/roadmap/<model>.md` |

## Entries

"""


def entries():
    out = []
    for path in sorted(KNOWLEDGE.glob("*.md")):
        if path.name == "index.md":
            continue
        head = None
        for line in path.read_text().splitlines():
            if line.startswith("# "):
                head = line[2:].strip()
                break
        if head is None:
            sys.exit(f"{path.name}: no `# ` heading - every entry states its own id and title")
        m = re.match(r"^([0-9]+[a-z]?)\.\s+(.*)$", head)
        if not m:
            sys.exit(f"{path.name}: heading {head!r} is not `# <id>. <title>`")
        out.append((m.group(1), m.group(2), path.name))
    return out


def render(rows):
    body = ["| # | finding | file |", "|---|---|---|"]
    for ident, title, name in rows:
        # The title may carry inline code; a pipe inside it would split the row.
        safe = title.replace("|", "\\|")
        body.append(f"| {ident} | {safe} | [`{name}`]({name}) |")
    return HEADER + "\n".join(body) + "\n"


def main():
    rows = entries()
    seen = {}
    for ident, _title, name in rows:
        if ident in seen:
            sys.exit(
                f"duplicate id {ident}: {seen[ident]} and {name} both answer to the same "
                f"citation, so a reference to #{ident} resolves to whichever a reader "
                f"finds first. Give the newer finding the next free number."
            )
        seen[ident] = name
    want = render(rows)
    if "--check" in sys.argv:
        have = INDEX.read_text() if INDEX.exists() else ""
        if have != want:
            sys.exit(
                "knowledge index is out of date - run `make knowledge-index` and commit the result"
            )
        print(f"knowledge index up to date ({len(rows)} entries)")
        return
    INDEX.write_text(want)
    print(f"wrote {INDEX.relative_to(ROOT)} ({len(rows)} entries)")


if __name__ == "__main__":
    main()
