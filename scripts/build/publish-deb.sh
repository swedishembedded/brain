# Publish a signed Debian package to the GitHub release of a version tag.
#
#   publish-deb.sh --version V [--remote NAME] [--key KEYID]
#                  [--notes-file FILE] (--check | PACKAGE.deb)
#
# The release is the one for tag vV, which must exist locally, be the commit
# checked out (with no uncommitted changes to tracked files, so the package is
# built from exactly that commit) and already be on GitHub at the same commit.
# The release is created from that tag if it does not exist yet. The package
# is signed with a detached ASCII-armoured GnuPG signature (PACKAGE.deb.asc,
# verify with `gpg --verify PACKAGE.deb.asc PACKAGE.deb`) and both files are
# uploaded with --clobber, replacing a previous upload of the same name; any
# other build of the same package and architecture attached to the release
# (a different Debian revision) is deleted, so the release carries exactly
# one. Re-running is safe: it converges on the same assets.
#
# --check runs every precondition that does not need the package (tools,
# login, tag, signing key) and publishes nothing, so a caller can fail before
# a long build instead of after it.
#
#   --remote git remote whose GitHub repository gets the release (default:
#            origin)
#   --key    GnuPG key to sign with (default: GnuPG's default secret key)
#   --notes-file  body of a newly created release (default: generated by
#            GitHub from the commits since the previous release)
#
# Nothing here pushes: a tag GitHub does not have is reported with the
# command that pushes it.
set -euo pipefail

die() {
    printf 'error: %s\n' "$1" >&2
    shift
    local line
    for line in "$@"; do printf '       %s\n' "$line" >&2; done
    exit 1
}

usage() {
    sed -n '12,13p' "${BASH_SOURCE[0]}" | sed 's/^# *//' >&2
    exit 2
}

VERSION=""
REMOTE=origin
KEY=""
NOTES_FILE=""
CHECK_ONLY=false
DEB=""
while (($#)); do
    case "$1" in
        --version) VERSION="${2:?--version needs a value}"; shift 2 ;;
        --remote) REMOTE="${2:?--remote needs a value}"; shift 2 ;;
        --key) KEY="${2:?--key needs a value}"; shift 2 ;;
        --notes-file) NOTES_FILE="${2:?--notes-file needs a value}"; shift 2 ;;
        --check) CHECK_ONLY=true; shift ;;
        -h|--help) usage ;;
        -*) printf 'error: unknown option: %s\n' "$1" >&2; usage ;;
        *) [[ -z "$DEB" ]] || usage; DEB="$1"; shift ;;
    esac
done
[[ -n "$VERSION" ]] || usage
if $CHECK_ONLY; then [[ -z "$DEB" ]] || usage; else [[ -n "$DEB" ]] || usage; fi
TAG="v${VERSION}"

# --- tools ---------------------------------------------------------------
command -v gh >/dev/null 2>&1 || die "the GitHub CLI (gh) is not installed." \
    "Install it from https://cli.github.com (Debian/Ubuntu: 'sudo apt install gh')," \
    "then log in with 'gh auth login' and run this again."
command -v gpg >/dev/null 2>&1 || die "GnuPG (gpg) is not installed; it signs the package." \
    "Debian/Ubuntu: 'sudo apt install gnupg', then run this again."
command -v dpkg-deb >/dev/null 2>&1 || die "dpkg-deb is not installed; it reads the package's version." \
    "Debian/Ubuntu: 'sudo apt install dpkg', then run this again."

# --- the release tag is what is checked out ------------------------------
git rev-parse --show-toplevel >/dev/null 2>&1 || die "not inside a git repository."
git rev-parse -q --verify "refs/tags/${TAG}" >/dev/null || die "there is no tag ${TAG} for version ${VERSION}." \
    "Cut the release first (it creates the tag), or tag the release commit by hand:" \
    "  git tag -a ${TAG} -m 'Release ${TAG}'"
TAG_COMMIT="$(git rev-parse "${TAG}^{commit}")"
[[ "$(git rev-parse HEAD)" == "$TAG_COMMIT" ]] || die "HEAD is not the release tag ${TAG}, so the package would not be built from the release." \
    "Publish from the tag:  git checkout ${TAG}  (then run this again)," \
    "or from a separate checkout:  git worktree add ../release-${TAG} ${TAG}"
[[ -z "$(git status --porcelain --untracked-files=no)" ]] || die "the working tree has uncommitted changes, so the package would not be the release commit." \
    "See them with 'git status'; commit or stash them, or publish from a clean" \
    "checkout:  git worktree add ../release-${TAG} ${TAG}"

# --- GitHub ----------------------------------------------------------------
REMOTE_URL="$(git remote get-url "$REMOTE" 2>/dev/null)" || die "there is no git remote '${REMOTE}'." \
    "List the remotes with 'git remote -v' and name the GitHub one, e.g. RELEASE_REMOTE=<name> on the make command line."
REPO="$(printf '%s\n' "$REMOTE_URL" | sed -nE 's#^(git@github\.com:|ssh://git@github\.com/|https://github\.com/)([^/]+/[^/]+)$#\2#p')"
REPO="${REPO%.git}"
[[ -n "$REPO" ]] || die "the remote '${REMOTE}' (${REMOTE_URL}) is not a GitHub repository." \
    "List the remotes with 'git remote -v' and name the GitHub one, e.g. RELEASE_REMOTE=<name> on the make command line."

AUTH_ERR="$(gh auth status --hostname github.com 2>&1 >/dev/null)" || die "gh is not logged in to github.com." \
    "Log in with 'gh auth login' (choose GitHub.com), then run this again." \
    "gh said: ${AUTH_ERR}"

PERMISSION="$(gh repo view "$REPO" --json viewerPermission --jq .viewerPermission 2>&1)" || die "cannot read the GitHub repository ${REPO}." \
    "Check the remote ('git remote -v') and that your gh login can see it ('gh auth status')." \
    "gh said: ${PERMISSION}"
case "$PERMISSION" in
    ADMIN|MAINTAIN|WRITE) ;;
    *) die "your GitHub account has ${PERMISSION:-no} access to ${REPO}; publishing a release needs write access." \
        "Ask a maintainer of ${REPO} for write access, or log in as another account with 'gh auth login'." ;;
esac

if ! REMOTE_COMMIT="$(gh api "repos/${REPO}/commits/${TAG}" --jq .sha 2>&1)"; then
    [[ "$REMOTE_COMMIT" == *"(HTTP 404)"* || "$REMOTE_COMMIT" == *"(HTTP 422)"* ]] || die "could not ask GitHub for the tag ${TAG} in ${REPO}." \
        "gh said: ${REMOTE_COMMIT}" "Check your network and 'gh auth status', then run this again."
    die "GitHub does not have the tag ${TAG} in ${REPO}." \
        "Push it, then run this again:  git push ${REMOTE} ${TAG}"
fi
[[ "$REMOTE_COMMIT" == "$TAG_COMMIT" ]] || die "the tag ${TAG} on GitHub (${REMOTE_COMMIT}) is not the local one (${TAG_COMMIT})." \
    "One of them was moved. Decide which commit is the release; to replace GitHub's with" \
    "the local one:  git push --force ${REMOTE} ${TAG}"

# --- signing key -------------------------------------------------------------
if [[ -n "$KEY" ]]; then
    gpg --list-secret-keys --with-colons "$KEY" 2>/dev/null | grep -q '^sec' || die "GnuPG has no secret key '${KEY}' to sign with." \
        "List the keys you have with 'gpg --list-secret-keys', or create one with 'gpg --full-generate-key'."
else
    gpg --list-secret-keys --with-colons 2>/dev/null | grep -q '^sec' || die "GnuPG has no secret key to sign the package with." \
        "Create one with 'gpg --full-generate-key', publish its public half so users can verify" \
        "(e.g. 'gpg --armor --export <you@example.com>' into your GitHub profile's GPG keys), then run this again."
fi

if $CHECK_ONLY; then
    printf 'publish-deb: ready to publish %s to %s\n' "$TAG" "$REPO"
    exit 0
fi

# --- the package -------------------------------------------------------------
[[ -f "$DEB" ]] || die "package not found: ${DEB}"
DEB_VERSION="$(dpkg-deb -f "$DEB" Version)" || die "${DEB} is not a Debian package dpkg-deb can read."
# The upstream part must be the tag's version; a Debian revision (-1) may follow.
[[ "$DEB_VERSION" == "$VERSION" || "$DEB_VERSION" =~ ^"$VERSION"-[0-9A-Za-z.+~]+$ ]] || die "${DEB} is version ${DEB_VERSION}, not the tag's ${VERSION}." \
    "Rebuild the package from ${TAG}."
PACKAGE="$(dpkg-deb -f "$DEB" Package)"
ARCH="$(dpkg-deb -f "$DEB" Architecture)"
NAME="$(basename "$DEB")"

SIGN_ARGS=(--yes --armor --detach-sign --output "${DEB}.asc")
[[ -z "$KEY" ]] || SIGN_ARGS+=(--local-user "$KEY")
gpg "${SIGN_ARGS[@]}" "$DEB" || die "GnuPG could not sign ${DEB}." \
    "If it asked for a passphrase and failed, check that gpg-agent can prompt ('echo test | gpg --clearsign')."
gpg --verify "${DEB}.asc" "$DEB" 2>/dev/null || die "the signature just made for ${DEB} does not verify."

# --- the release -------------------------------------------------------------
if ! gh release view "$TAG" --repo "$REPO" >/dev/null 2>&1; then
    NOTES_ARGS=(--generate-notes)
    [[ -z "$NOTES_FILE" ]] || NOTES_ARGS=(--notes-file "$NOTES_FILE")
    if OUT="$(gh release create "$TAG" --repo "$REPO" --verify-tag --title "$TAG" "${NOTES_ARGS[@]}" 2>&1)"; then
        printf 'publish-deb: created release %s\n' "$TAG"
    else
        # A tag-triggered workflow may have created it in the meantime.
        gh release view "$TAG" --repo "$REPO" >/dev/null 2>&1 || die "could not create the GitHub release ${TAG} in ${REPO}." \
            "gh said: ${OUT}" "Fix that and run this again; nothing has been uploaded."
    fi
fi

OUT="$(gh release upload "$TAG" "$DEB" "${DEB}.asc" --repo "$REPO" --clobber 2>&1)" || die "uploading ${NAME} to release ${TAG} failed." \
    "gh said: ${OUT}" "Running this again is safe: it replaces whatever was partly uploaded."

# Other builds of this package for this architecture (another Debian revision).
ASSETS="$(gh release view "$TAG" --repo "$REPO" --json assets --jq '.assets[].name' 2>&1)" || die "could not list the assets of release ${TAG}." \
    "gh said: ${ASSETS}"
while IFS= read -r asset; do
    case "$asset" in
        "$NAME"|"${NAME}.asc") ;;
        "${PACKAGE}_"*"_${ARCH}.deb"|"${PACKAGE}_"*"_${ARCH}.deb.asc")
            OUT="$(gh release delete-asset "$TAG" "$asset" --repo "$REPO" --yes 2>&1)" || die "could not delete the superseded asset ${asset}." \
                "gh said: ${OUT}"
            printf 'publish-deb: removed superseded %s\n' "$asset" ;;
    esac
done <<<"$ASSETS"

grep -qxF "$NAME" <<<"$ASSETS" && grep -qxF "${NAME}.asc" <<<"$ASSETS" || die "the upload reported success but release ${TAG} does not list ${NAME} and its signature." \
    "Check https://github.com/${REPO}/releases/tag/${TAG} and run this again."

printf 'publish-deb: %s and %s.asc are on https://github.com/%s/releases/tag/%s\n' "$NAME" "$NAME" "$REPO" "$TAG"
