"""Regenerate the kernel catalogue table in README.md from crates/kernels/wgsl/.

The table is DERIVED, never hand-written: with ~360 kernels a hand-maintained
list is wrong within a week, and a wrong catalogue is worse than none because it
is the thing a reader consults before writing a new kernel (`docs/kernel-checklist.md`
§F.3: check for an existing faster sibling FIRST).

Every column comes from a signal in the source, not from judgement:

* **what / how** — the kernel's own leading comment block and its structure.
* **opt** — a STRUCTURAL rubric (see `LEVELS`), stated in the README legend.
  It describes the implementation's parallel structure, not measured
  throughput; measured numbers live in `docs/performance/`.
* **cpu** — whether `backend-cpu`'s Cranelift JIT can execute it. The JIT splits
  a kernel body at ONE top-level `workgroupBarrier()` and no more, so a kernel
  with two or more does not merely fail there — it corrupts memory
  (`docs/lessons.md` #26). `native` marks the 32 kernels that additionally have
  a hand-written AVX2 fast path.
* **gpu** — every kernel; the WGSL *is* the GPU path. `256` marks the ones
  declaring `@workgroup_size(256)`, which requires a device whose queried
  `DeviceCaps::max_workgroup_size` allows it (256 is the WebGPU floor).
* **npu** — the Intel NPU never runs WGSL at all: it is a whole-graph OpenVINO
  path fed by an exported ONNX graph. A tick means `crates/npu`'s topology DSL
  can emit an equivalent op, so a graph containing this kernel is expressible.
* **quant** — the kernel is part of the INT8 path (packed weights, DP4A, the
  activation quantizers, or int8 paged KV).

Usage:
    scripts/build/gen-kernel-table.py            # rewrite README.md in place
    scripts/build/gen-kernel-table.py --check    # exit 1 if README.md is stale
"""

import pathlib
import re
import sys

# This script lives in scripts/build/, so the repo root is two levels up.
ROOT = pathlib.Path(__file__).resolve().parents[2]
WGSL = ROOT / "crates" / "kernels" / "wgsl"
README = ROOT / "README.md"

BEGIN = "<!-- BEGIN KERNEL TABLE (generated by scripts/build/gen-kernel-table.py) -->"
END = "<!-- END KERNEL TABLE -->"

LEVELS = {
    5: "register-tiled / DP4A / split-K — a thread owns a register block of the output",
    4: "workgroup-cooperative — threads share a reduction through workgroup memory",
    3: "coalesced elementwise or gather — one thread per output, no serial reduction",
    2: "one thread per output with a serial reduction over a Params-bounded axis",
    1: "one thread walking a DEEP (3+ nested) serial reduction — the `conv2d_dx` shape",
}

# Kernels with a hand-written AVX2 fast path in `backend_cpu::{fast_ops,fast_conv}`,
# read from the `FastIdx` struct so this cannot drift from the backend.
def native_cpu_kernels():
    src = (ROOT / "crates" / "backend-cpu" / "src" / "lib.rs").read_text()
    block = re.search(r"struct FastIdx \{(.*?)\n\}", src, re.S)
    if not block:
        return set()
    return set(re.findall(r"^\s{4}([a-z0-9_]+): Option<usize>", block.group(1), re.M))

# Op families `crates/npu`'s ONNX topology DSL can emit. The NPU runs a whole
# compiled graph, never a WGSL kernel, so this says "expressible", not "runs".
NPU_EMITTABLE = (
    "matmul", "add", "mul", "sub", "reshape", "transpose", "softmax", "gather",
    "slice", "concat", "silu", "rmsnorm", "layernorm", "gn_", "group_norm",
    "conv", "linear_quant", "bn_", "relu", "gelu", "sigmoid", "tanh", "pool",
    "resize", "upsample", "embed", "pad", "crop",
)

QUANT_MARKERS = ("_i8", "i8_", "quant", "max_abs", "dequant", "bsq", "vq_")


def header_comment(text):
    """The leading `//` block, as a list of stripped lines."""
    out = []
    for line in text.splitlines():
        s = line.strip()
        if s.startswith("//"):
            out.append(s[2:].strip())
        elif not s:
            if out:
                break
        else:
            break
    return out


def summarise(lines):
    """First sentence of the header block — what the kernel does."""
    if not lines:
        return "—"
    buf = []
    for ln in lines:
        if not ln:
            break
        buf.append(ln)
        if ln.endswith(".") and len(" ".join(buf)) > 20:
            break
    s = " ".join(buf).strip()
    # Cut at the first sentence end that leaves something substantial.
    m = re.search(r"^(.{25,}?[.:])(\s|$)", s)
    if m:
        s = m.group(1)
    s = s.rstrip(".:").strip()
    return s or "—"


def structure(name, text):
    """(how-it-works phrase, optimisation level, barrier count, workgroup size)."""
    wg = re.search(r"@workgroup_size\((\d+)", text)
    wg = int(wg.group(1)) if wg else 64
    barriers = text.count("workgroupBarrier")
    shared = "var<workgroup>" in text
    dp4a = "dot4I8Packed" in text
    # A loop whose bound is a uniform field is a serial reduction on one lane.
    # Count them: one is a reduction, three or more nested is the shape that made
    # `conv2d_dx` walk Cout*K*K per input pixel (41% of a VQGAN backward before
    # it was lowered to a GEMM), which is a different class of problem.
    serial_loops = len(re.findall(r"for\s*\(\s*var\s+\w+[^;]*;\s*\w+\s*<\s*p\.", text))
    serial_loop = serial_loops > 0

    tags = []
    if dp4a:
        tags.append("DP4A packed int8")
    if re.search(r"_reg\d?$|_reg_|_reg\b", name) or "rA[" in text or "acc[" in text:
        tags.append("register block")
    if shared:
        tags.append(f"{wg}-thread workgroup tile")
    if barriers:
        tags.append(f"{barriers} barrier" + ("s" if barriers > 1 else ""))
    if not tags:
        tags.append("one thread per output element")
        if serial_loops >= 3:
            tags.append(f"{serial_loops} nested serial reductions")
        elif serial_loop:
            tags.append("serial inner reduction")
    tags.append(f"@wg {wg}")

    if dp4a or "splitk" in name or re.search(r"_reg\d?$", name):
        level = 5
    elif shared and barriers:
        level = 4
    elif name.endswith(("_part", "_final", "_rows", "_wg", "2")) and serial_loop:
        level = 4
    elif serial_loops >= 3:
        level = 1
    elif serial_loop:
        level = 2
    else:
        level = 3
    return " + ".join(tags), level, barriers, wg


def cell(name, text, barriers, wg, native):
    # Three distinct CPU cases, and collapsing them would mislead:
    #   `native`      — a hand-written AVX2 path runs instead of the JIT.
    #   `native only` — that path is the ONLY way it works here; the WGSL has
    #                   >1 barrier, so a `BRAIN_NO_FASTCONV=1` or non-AVX2 host
    #                   falls back to a JIT that corrupts memory on it.
    #   `✗`           — >1 barrier and no native path.
    if name in native:
        cpu = "native" if barriers <= 1 else "native only"
    else:
        cpu = "✓" if barriers <= 1 else "✗"
    gpu = "✓ (256)" if wg >= 256 else "✓"
    npu = "✓" if any(k in name for k in NPU_EMITTABLE) else "—"
    quant = "int8" if any(k in name for k in QUANT_MARKERS) else "—"
    return cpu, gpu, npu, quant


def esc(s):
    return s.replace("|", "\\|")


def build_table():
    native = native_cpu_kernels()
    rows = []
    counts = {"lvl": {}, "cpu_no": 0, "quant": 0, "npu": 0}
    for f in sorted(WGSL.glob("*.wgsl")):
        name = f.stem
        text = f.read_text()
        head = header_comment(text)
        what = summarise(head)
        how, level, barriers, wg = structure(name, text)
        cpu, gpu, npu, quant = cell(name, text, barriers, wg, native)
        rel = f"crates/kernels/wgsl/{name}.wgsl"
        rows.append(
            f"| [`{name}`]({rel}) | {esc(what)} | {esc(how)} | {level}/5 | {cpu} | {gpu} | {npu} | {quant} |"
        )
        counts["lvl"][level] = counts["lvl"].get(level, 0) + 1
        counts["cpu_no"] += cpu == "✗"
        counts["quant"] += quant == "int8"
        counts["npu"] += npu == "✓"

    n = len(rows)
    lvl = counts["lvl"]
    out = [BEGIN, ""]
    out.append(f"**{n} kernels.** Generated by `scripts/build/gen-kernel-table.py`")
    out.append("(`make kernels-table`); `make kernels-table/check` fails if this table")
    out.append("has drifted from the sources. Do not edit the rows by hand.")
    out.append("")
    out.append("**opt** is a *structural* rubric — how the work is parallelised, not how fast it")
    out.append("measured. Measured numbers live in [`docs/performance/`](docs/performance/overview.md),")
    out.append("and a kernel can be 5/5 structurally and still be a defect at a given shape.")
    out.append("")
    for k in sorted(LEVELS, reverse=True):
        out.append(f"* **{k}/5** — {LEVELS[k]} ({lvl.get(k, 0)} kernels)")
    out.append("")
    out.append("**cpu** — `backend-cpu`'s Cranelift JIT splits a kernel body at ONE top-level")
    out.append("`workgroupBarrier()` and no more; with two or more it does not fail cleanly, it")
    out.append("**corrupts memory** ([`docs/lessons.md`](docs/lessons.md) #26), so those are `✗`")
    out.append(f"({counts['cpu_no']} kernels). `native` marks the {len(native)} kernels with a hand-written")
    out.append("AVX2 path that runs instead of the JIT; `native only` means that path is the *only*")
    out.append("way the kernel works there, because its WGSL has >1 barrier — under")
    out.append("`BRAIN_NO_FASTCONV=1` or on a non-AVX2 host it would fall back to the JIT and")
    out.append("corrupt memory. A `✓` says the JIT *can* run it, not that the selector will choose")
    out.append("it: `DeviceCaps::workgroup_reductions` is `false` on this backend, so cooperative")
    out.append("variants are deliberately not selected there.")
    out.append("**gpu** — every kernel; `(256)` needs a device whose")
    out.append("queried `DeviceCaps::max_workgroup_size` allows it (256 is the WebGPU floor).")
    out.append("**npu** — the Intel NPU never runs WGSL: it is a whole-graph OpenVINO path fed by")
    out.append(f"an exported ONNX graph, so `✓` means `crates/npu`'s topology DSL can emit an")
    out.append(f"equivalent op ({counts['npu']} kernels), not that this file runs there.")
    out.append(f"**quant** — part of the INT8 path ({counts['quant']} kernels).")
    out.append("")
    out.append("| kernel | what it does | how | opt | cpu | gpu | npu | quant |")
    out.append("|---|---|---|---|---|---|---|---|")
    out.extend(rows)
    out.append("")
    out.append(END)
    return "\n".join(out)


def main():
    check = "--check" in sys.argv
    table = build_table()
    text = README.read_text()
    if BEGIN in text and END in text:
        new = re.sub(
            re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: table, text, flags=re.S
        )
    else:
        new = text.rstrip() + "\n\n## Kernel catalogue\n\n" + table + "\n"

    if check:
        if new != text:
            print(
                "README.md's kernel table is stale — run `make kernels-table`.",
                file=sys.stderr,
            )
            return 1
        print(f"kernel table up to date ({len(list(WGSL.glob('*.wgsl')))} kernels)")
        return 0

    README.write_text(new)
    print(f"kernel table: {len(list(WGSL.glob('*.wgsl')))} kernels written to README.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
