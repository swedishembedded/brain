"""Regenerate README.md's kernel catalogue from metadata the kernels DECLARE.

Every column comes from an `@`-tagged field in the kernel's own header:

    // @what  Register-tiled matmul (out = x @ Wᵀ), ...
    // @how   register block per thread, 256-thread workgroup tile, 3 barriers
    // @opt   5
    // @cpu   native-only
    // @gpu   yes-wg256
    // @npu   yes
    // @quant none

This script only reads and formats them — it infers nothing. That matters: the
catalogue is what `docs/kernel-checklist.md` §F.3 tells you to consult before
writing a kernel, and a table built from heuristics run over the code is a table
of guesses. The author states the facts next to the kernel; a wrong row is then
a wrong claim in the source, fixable where the knowledge is.

Four of the seven fields are ALSO mechanically checkable, and are cross-checked
on every run — a declaration that contradicts the code is an error, not a
preference, so the block cannot rot into fiction:

  * `@cpu`   vs the top-level `workgroupBarrier()` count (the JIT splits at one
             and no more; two or more corrupts memory — `docs/lessons.md` #26)
  * `@gpu`   vs the declared `@workgroup_size`
  * `@quant` vs the presence of `dot4I8Packed`
  * `@opt 5` vs the presence of a register block / DP4A / split-K

`@what`, `@how` and `@npu` are author judgement and are taken as given.

Usage:
    scripts/build/gen-kernel-table.py            # rewrite README.md in place
    scripts/build/gen-kernel-table.py --check    # exit 1 if stale or invalid
"""

import pathlib
import re
import sys

# This script lives in scripts/build/, so the repo root is two levels up.
ROOT = pathlib.Path(__file__).resolve().parents[2]
WGSL = ROOT / "crates" / "kernels" / "wgsl"
README = ROOT / "README.md"

BEGIN = "<!-- BEGIN KERNEL TABLE (generated by scripts/build/gen-kernel-table.py) -->"
END = "<!-- END KERNEL TABLE -->"

FIELDS = ("what", "how", "opt", "cpu", "gpu", "npu", "quant")

LEVELS = {
    5: "register-tiled / DP4A / split-K — a thread owns a register block of the output",
    4: "workgroup-cooperative — threads share a reduction through workgroup memory",
    3: "coalesced elementwise or gather — one thread per output, no serial reduction",
    2: "one thread per output with a serial reduction over a Params-bounded axis",
    1: "one thread walking a DEEP (3+ nested) serial reduction — the `conv2d_dx` shape",
}

CPU_CELL = {"yes": "✓", "no": "✗", "native": "native", "native-only": "native only"}
GPU_CELL = {"yes": "✓", "yes-wg256": "✓ (256)", "no": "✗"}
NPU_CELL = {"yes": "✓", "no": "—"}
QUANT_CELL = {"int8": "int8", "none": "—"}


def parse_meta(text):
    """The declared `@` block, or `None` for each field it does not declare."""
    meta = {}
    for f in FIELDS:
        m = re.search(r"^//\s*@%s\s+(.*?)\s*$" % f, text, re.M)
        meta[f] = m.group(1) if m else None
    return meta


def cross_check(name, text, meta):
    """Errors where a declaration contradicts what the code actually is."""
    errs = []
    barriers = text.count("workgroupBarrier")
    wg = re.search(r"@workgroup_size\((\d+)", text)
    wg = int(wg.group(1)) if wg else 64
    dp4a = "dot4I8Packed" in text

    cpu = meta["cpu"]
    if cpu not in CPU_CELL:
        errs.append(f"@cpu {cpu!r} is not one of {sorted(CPU_CELL)}")
    else:
        if cpu in ("yes", "native") and barriers > 1:
            errs.append(
                f"@cpu {cpu} but {barriers} barriers — the CPU JIT splits at ONE and "
                "corrupts memory beyond that (lessons #26); use `no` or `native-only`"
            )
        if cpu in ("no", "native-only") and barriers <= 1:
            errs.append(f"@cpu {cpu} but only {barriers} barrier(s) — the JIT can run this")

    want_gpu = "yes-wg256" if wg >= 256 else "yes"
    if meta["gpu"] != want_gpu:
        errs.append(f"@gpu {meta['gpu']!r} but @workgroup_size({wg}) implies {want_gpu!r}")

    if dp4a and meta["quant"] != "int8":
        errs.append("@quant is not int8 but the kernel uses dot4I8Packed")

    if meta["opt"] == "5" and not (
        dp4a or "splitk" in name or re.search(r"_reg\d?$", name) or "rA[" in text
    ):
        errs.append("@opt 5 but no register block, DP4A or split-K is present")

    if meta["npu"] not in NPU_CELL:
        errs.append(f"@npu {meta['npu']!r} is not one of {sorted(NPU_CELL)}")
    if meta["quant"] not in QUANT_CELL:
        errs.append(f"@quant {meta['quant']!r} is not one of {sorted(QUANT_CELL)}")
    if meta["opt"] not in {"1", "2", "3", "4", "5"}:
        errs.append(f"@opt {meta['opt']!r} is not 1-5")
    return errs


def esc(s):
    return s.replace("|", "\\|")


def build_table():
    rows, problems = [], []
    counts = {"lvl": {}, "cpu_no": 0, "native": 0, "quant": 0, "npu": 0}

    for f in sorted(WGSL.glob("*.wgsl")):
        name, text = f.stem, f.read_text()
        meta = parse_meta(text)
        missing = [k for k in FIELDS if meta[k] is None]
        if missing:
            problems.append(f"{name}.wgsl: missing @{', @'.join(missing)}")
            continue
        for e in cross_check(name, text, meta):
            problems.append(f"{name}.wgsl: {e}")

        lvl = int(meta["opt"]) if meta["opt"] in {"1", "2", "3", "4", "5"} else 0
        rel = f"crates/kernels/wgsl/{name}.wgsl"
        rows.append(
            f"| [`{name}`]({rel}) | {esc(meta['what'])} | {esc(meta['how'])} | {lvl}/5 "
            f"| {CPU_CELL.get(meta['cpu'], '?')} | {GPU_CELL.get(meta['gpu'], '?')} "
            f"| {NPU_CELL.get(meta['npu'], '?')} | {QUANT_CELL.get(meta['quant'], '?')} |"
        )
        counts["lvl"][lvl] = counts["lvl"].get(lvl, 0) + 1
        counts["cpu_no"] += meta["cpu"] == "no"
        counts["native"] += str(meta["cpu"]).startswith("native")
        counts["quant"] += meta["quant"] == "int8"
        counts["npu"] += meta["npu"] == "yes"

    n, lvl = len(rows), counts["lvl"]
    out = [BEGIN, ""]
    out += [
        f"**{n} kernels.** Every column is a field the kernel DECLARES in its own header",
        "(`@what` / `@how` / `@opt` / `@cpu` / `@gpu` / `@npu` / `@quant`) — nothing here is",
        "inferred. `make kernels-table` regenerates; `make kernels-table/check` fails when a",
        "kernel is missing a field, when a declaration contradicts the code, or when this",
        "table has drifted. Edit the kernel's header, never the row.",
        "",
        "**opt** is a *structural* rubric — how the work is parallelised, not how fast it",
        "measured. Measured numbers live in [`docs/performance/`](docs/performance/overview.md);",
        "a kernel can be 5/5 structurally and still be a defect at a given shape.",
        "",
    ]
    for k in sorted(LEVELS, reverse=True):
        out.append(f"* **{k}/5** — {LEVELS[k]} ({lvl.get(k, 0)} kernels)")
    out += [
        "",
        "**cpu** — `backend-cpu`'s Cranelift JIT splits a kernel body at ONE top-level",
        "`workgroupBarrier()` and no more; with two or more it does not fail cleanly, it",
        "**corrupts memory** ([`docs/lessons.md`](docs/lessons.md) #26), so those are `✗`",
        f"({counts['cpu_no']} kernels) — cross-checked against the barrier count on every run.",
        f"`native` marks the {counts['native']} kernels with a hand-written AVX2 path that runs instead",
        "of the JIT; `native only` means that path is the *only* way it works there, because",
        "its WGSL has >1 barrier — under `BRAIN_NO_FASTCONV=1` or on a non-AVX2 host it would",
        "fall back to the JIT and corrupt memory. A `✓` says the JIT *can* run it, not that the",
        "selector will choose it: `DeviceCaps::workgroup_reductions` is `false` there, so",
        "cooperative variants are deliberately not selected.",
        "",
        "**gpu** — every kernel; `✓ (256)` needs a device whose queried",
        "`DeviceCaps::max_workgroup_size` allows it (256 is the WebGPU floor).",
        "**npu** — the Intel NPU never runs WGSL: it is a whole-graph OpenVINO path fed by an",
        "exported ONNX graph, so `✓` means `crates/npu`'s topology DSL can emit an equivalent",
        f"op ({counts['npu']} kernels), not that this file runs there.",
        f"**quant** — part of the INT8 path ({counts['quant']} kernels).",
        "",
        "| kernel | what it does | how | opt | cpu | gpu | npu | quant |",
        "|---|---|---|---|---|---|---|---|",
    ]
    out += rows
    out += ["", END]
    return "\n".join(out), problems


def main():
    check = "--check" in sys.argv
    table, problems = build_table()
    if problems:
        print("kernel metadata is invalid:", file=sys.stderr)
        for p in problems:
            print(f"  {p}", file=sys.stderr)
        print(
            "\nEach kernel's header must declare @what/@how/@opt/@cpu/@gpu/@npu/@quant "
            "and agree with its code. `scripts/build/seed-kernel-meta.py` seeds a new "
            "kernel's block; edit it by hand after that.",
            file=sys.stderr,
        )
        return 1

    text = README.read_text()
    if BEGIN in text and END in text:
        new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: table, text, flags=re.S)
    else:
        new = text.rstrip() + "\n\n## Kernel catalogue\n\n" + table + "\n"

    if check:
        if new != text:
            print("README.md's kernel table is stale — run `make kernels-table`.", file=sys.stderr)
            return 1
        print(f"kernel table up to date ({n_kernels()} kernels, all fields declared)")
        return 0

    README.write_text(new)
    print(f"kernel table: {n_kernels()} kernels written to README.md")
    return 0


def n_kernels():
    return len(list(WGSL.glob("*.wgsl")))


if __name__ == "__main__":
    sys.exit(main())
