"""Regenerate the native CUDA kernel catalogue from the registry that IS it.

The single source of truth is `crates/kernels-cuda/src/lib.rs`'s `ALL` table:
each entry states its own name, operator, tier, compute-capability floor,
entry point and one-line description, and embeds its source with
`include_str!`. This script reads that table and renders it; it infers
nothing and it never edits the crate.

Two things it checks that nothing else can:

  1. ORPHANED SOURCE - every `.cu` file under `crates/kernels-cuda/cu/` must
     be embedded by exactly one registry entry. A kernel file the registry
     does not list is a kernel nothing can dispatch, nothing compiles and
     nothing tests, sitting in the tree looking like shipped functionality.
     The crate's own Rust invariant test cannot see this: `include_str!`
     proves registry -> file, never file -> registry.
  2. CATALOGUE DRIFT - the published table must match the registry. The
     failure this prevents is a page claiming a kernel that was deleted, or
     silently omitting one that was added.

The per-entry semantic invariants (unique names, a tier that a source file
can honestly claim, an entry point that exists in the text, a capability
floor consistent with the instructions used) are NOT re-implemented here:
they live in `kernels_cuda::check_table` and are asserted by that crate's own
test. One checker, in the language that owns the data.

Deliberately NOT the WGSL catalogue generator with a second mode bolted on:
that script derives const names from `.wgsl` stems, compiles every entry on
the test device, demands a cost formula per entry, and cross-checks five
WGSL-text-specific metadata fields against the shader body. None of those
have any purchase on CUDA C++, so sharing the script would mean one file
hosting two disjoint validators.

A future addition, once the backend can compile at all: check that each
declared kernel compiles under NVRTC for its own declared floor. That needs a
CUDA toolkit, so it is an ADDITION to these checks, never a replacement -
these run anywhere.

Usage:
    scripts/build/gen-cuda-kernel-table.py            # rewrite the catalogue
    scripts/build/gen-cuda-kernel-table.py --check    # exit 1 if stale/invalid
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CRATE = ROOT / "crates" / "kernels-cuda"
REGISTRY = CRATE / "src" / "lib.rs"
CU = CRATE / "cu"
PAGE = ROOT / "docs" / "reference" / "kernels-cuda.md"

BEGIN = "<!-- BEGIN CUDA KERNEL TABLE (generated by scripts/build/gen-cuda-kernel-table.py) -->"
END = "<!-- END CUDA KERNEL TABLE -->"

# The `pub const ALL: &[CudaKernel] = &[ ... ];` body, and one entry inside it.
ALL_BLOCK = re.compile(r"pub const ALL: &\[CudaKernel\] = &\[(.*?)\];", re.S)
ENTRY = re.compile(
    r"CudaKernel\s*\{(?P<body>[^{}]*?)\}",
    re.S,
)
FIELD = {
    "name": re.compile(r'name:\s*"([^"]*)"'),
    "op": re.compile(r"op:\s*Op::(\w+)"),
    "source": re.compile(r"source:\s*ImplSource::(\w+)"),
    "min_cc": re.compile(r"min_cc:\s*\((\d+)\s*,\s*(\d+)\)"),
    "entry": re.compile(r'entry:\s*"([^"]*)"'),
    "what": re.compile(r'what:\s*"((?:[^"\\]|\\.)*)"'),
    "src": re.compile(r'src:\s*include_str!\("([^"]*)"\)'),
}


def parse_registry(text):
    """Every entry of `ALL`, as dicts, in declaration order."""
    block = ALL_BLOCK.search(text)
    if block is None:
        sys.exit("gen-cuda-kernel-table: no `pub const ALL: &[CudaKernel]` in the registry")
    entries = []
    for m in ENTRY.finditer(block.group(1)):
        body = m.group("body")
        row = {}
        for field, pattern in FIELD.items():
            hit = pattern.search(body)
            if hit is None:
                sys.exit(f"gen-cuda-kernel-table: a registry entry has no `{field}`:\n{body}")
            row[field] = hit.groups()
        entries.append(
            {
                "name": row["name"][0],
                "op": row["op"][0],
                "source": row["source"][0],
                "min_cc": f"{row['min_cc'][0]}.{row['min_cc'][1]}",
                "entry": row["entry"][0],
                "what": row["what"][0],
                "src": row["src"][0],
            }
        )
    return entries


def check_sources(entries):
    """Registry <-> `cu/` correspondence, both directions."""
    errs = []
    embedded = {}
    for e in entries:
        path = (REGISTRY.parent / e["src"]).resolve()
        if not path.is_file():
            errs.append(f'{e["name"]}: embeds {e["src"]}, which does not exist')
            continue
        if path in embedded:
            errs.append(f'{e["name"]}: embeds {e["src"]}, already embedded by {embedded[path]}')
        embedded[path] = e["name"]
    if CU.is_dir():
        for f in sorted(CU.glob("*.cu")):
            if f.resolve() not in embedded:
                errs.append(
                    f"cu/{f.name}: no registry entry embeds this file - a kernel nothing "
                    "dispatches, compiles or tests"
                )
    return errs


def render(entries):
    lines = [
        BEGIN,
        "",
        "Every column is stated by the kernel's own registry entry in "
        "`crates/kernels-cuda` - nothing here is inferred. `make cuda-table` "
        "regenerates this block; `make cuda-table/check` fails when a kernel "
        "source is not registered, or when this table has drifted from the "
        "registry. Edit the registry, never the row.",
        "",
    ]
    if not entries:
        lines += [
            "**No hand-written CUDA kernel ships yet.** The native CUDA backend "
            "enumerates devices and states its tier policy, but cannot yet compile "
            "or launch anything, so there is no kernel to list. This page, its "
            "registry and its gate exist first on purpose: the first kernel to land "
            "arrives into something that checks what it claims about itself.",
            "",
        ]
    else:
        lines += [
            "| kernel | op | tier | min cc | entry point | what |",
            "|---|---|---|---|---|---|",
        ]
        for e in entries:
            lines.append(
                f'| `{e["name"]}` | {e["op"]} | {e["source"].lower()} | {e["min_cc"]} '
                f'| `{e["entry"]}` | {e["what"]} |'
            )
        lines.append("")
    lines += [
        "**tier** - `tuned` is hand-written for this backend, optionally "
        "specialised to a queried device capability. It is the only tier a file "
        "in this tree can claim: a `generated` kernel is emitted from the "
        "portable WGSL reference at run time and has no source file here, and "
        "the `reference` tier IS that WGSL.",
        "",
        "**min cc** - the lowest compute capability the kernel's own TEXT is "
        "valid on, decided by the instructions it uses. It is not a statement "
        "about any card: which kernel a device gets is resolved at run time "
        "against the capability the driver was asked for, highest eligible "
        "floor first.",
        "",
        END,
    ]
    return "\n".join(lines)


def main():
    check = "--check" in sys.argv[1:]
    entries = parse_registry(REGISTRY.read_text())
    errs = check_sources(entries)
    if errs:
        print("cuda-table: FAIL")
        for e in errs:
            print(f"  {e}")
        return 1

    page = PAGE.read_text()
    if BEGIN not in page or END not in page:
        sys.exit(f"gen-cuda-kernel-table: {PAGE.name} has no generated-table markers")
    head, rest = page.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    updated = head + render(entries) + tail

    if check:
        if updated != page:
            print("cuda-table: FAIL - the catalogue has drifted from the registry.")
            print("  Run `make cuda-table` and commit the result.")
            return 1
        print(f"cuda-table: ok, {len(entries)} kernel(s), catalogue current")
        return 0

    PAGE.write_text(updated)
    print(f"cuda-table: wrote {len(entries)} kernel(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
