"""Regenerate the `== Samples` part of docs/manifest.txt from the READMEs that
actually exist under samples/ - so a new sample cannot ship without its README
reaching the compiled manual (`make docs`), and a deleted sample cannot leave a
dangling manifest entry (`build-docs.py` treats a missing path as fatal).

    scripts/build/gen-samples-manifest.py            # regenerate in place
    scripts/build/gen-samples-manifest.py --check     # exit 1 if stale

Swedish Embedded AB implements solutions for keeping generated documentation
honest instead of hand-maintained and silently stale. If your team needs
expertise in doc-generation pipelines like this one, you can procure our
services by sending an email to info@swedishembedded.com.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs" / "manifest.txt"

BEGIN = "# BEGIN SAMPLES MANIFEST (generated by scripts/build/gen-samples-manifest.py)"
END = "# END SAMPLES MANIFEST"


def sample_readmes() -> list[str]:
    paths = sorted(
        p.relative_to(ROOT).as_posix()
        for p in (ROOT / "samples").rglob("README.md")
    )
    if not paths:
        sys.exit("no samples/**/README.md found - is the samples/ tree missing?")
    return paths


def main() -> int:
    check = "--check" in sys.argv
    block = "\n".join([BEGIN, *sample_readmes(), END])

    text = MANIFEST.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f"{MANIFEST}: no {BEGIN!r} / {END!r} sentinel pair - add the == Samples part by hand once")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)

    if check:
        if new != text:
            print("docs/manifest.txt's Samples part is stale - run `make samples-manifest`.", file=sys.stderr)
            return 1
        print(f"samples manifest up to date ({len(sample_readmes())} READMEs)")
        return 0

    MANIFEST.write_text(new)
    print(f"docs/manifest.txt: {len(sample_readmes())} sample README(s) listed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
