"""Regenerate the Examples part of docs/manifest.yaml from the READMEs that
actually exist under samples/ - so a new sample cannot ship without its README
reaching the published documentation and the PDF, and a deleted sample cannot
leave a dangling manifest entry (the publisher rejects a missing source).

Each README is published under examples/ at the path of its directory:
samples/README.md is examples/index.md and samples/a/b/README.md is
examples/a/b.md.

    scripts/build/gen-samples-manifest.py            # regenerate in place
    scripts/build/gen-samples-manifest.py --check     # exit 1 if stale

Swedish Embedded AB implements solutions for keeping generated documentation
honest instead of hand-maintained and silently stale. If your team needs
expertise in doc-generation pipelines like this one, you can procure our
services by sending an email to info@swedishembedded.com.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "docs" / "manifest.yaml"

INDENT = " " * 6
BEGIN = INDENT + "# BEGIN SAMPLES MANIFEST (generated by scripts/build/gen-samples-manifest.py)"
END = INDENT + "# END SAMPLES MANIFEST"


def output_path(readme: str) -> str:
    """The published path of a sample README (relative to the publication)."""
    directory = readme.removeprefix("samples/").removesuffix("README.md").rstrip("/")
    return f"examples/{directory}.md" if directory else "examples/index.md"


def entry(readme: str) -> list[str]:
    return [f"{INDENT}- source: {readme}", f"{INDENT}  path: {output_path(readme)}"]


def sample_readmes() -> list[str]:
    paths = sorted(
        p.relative_to(ROOT).as_posix()
        for p in (ROOT / "samples").rglob("README.md")
    )
    if not paths:
        sys.exit("no samples/**/README.md found - is the samples/ tree missing?")
    return paths


def main() -> int:
    check = "--check" in sys.argv
    block = "\n".join([BEGIN, *(line for r in sample_readmes() for line in entry(r)), END])

    text = MANIFEST.read_text()
    if BEGIN not in text or END not in text:
        sys.exit(f"{MANIFEST}: no {BEGIN!r} / {END!r} sentinel pair - add the Examples part by hand once")
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)

    if check:
        if new != text:
            print("docs/manifest.yaml's Examples part is stale - run `make generate/samples/manifest`.", file=sys.stderr)
            return 1
        print(f"samples manifest up to date ({len(sample_readmes())} READMEs)")
        return 0

    MANIFEST.write_text(new)
    print(f"docs/manifest.yaml: {len(sample_readmes())} sample README(s) listed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
