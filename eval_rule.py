"""
eval_rule.py — measure how well a checkpoint learned the toy rule, so you can
tell whether one set of weights is better than another.

Because the corpus is generated by a known deterministic rule
    data[i] = (data[i-2] + table[data[i-1]]) % vocab
we have exact ground truth for any input, so "correctness" is *measured*, not
estimated.

Two distinct numbers are reported, and the distinction matters:
  * new-orbit accuracy — overall rule-fit. Good for *comparing* checkpoints, but
    it is mostly RECALL: the predictive state is just (a,b) and there are only
    4096 of them, so a "new" orbit overwhelmingly revisits seen states.
  * accuracy on UNSEEN (a,b) states — the TRUE generalisation/extrapolation test
    (a model that merely memorised the transition table scores ~0% here).

Usage:
    python eval_rule.py --ckpt moe.pt
    python eval_rule.py --ckpt good.pt --compare baseline.pt     # side-by-side verdict
"""

from __future__ import annotations

import argparse

import numpy as np
import torch

import tiny_sparse_moe as m


def rule_table(seed: int, vocab: int) -> np.ndarray:
    # Must match make_toy_corpus: the table is the first draw from the corpus RNG.
    return np.random.default_rng(seed).permutation(vocab)


@torch.no_grad()
def batched_acc(model, seq: np.ndarray, ctx_len: int, max_samples: int) -> float:
    """Teacher-forced next-token accuracy: argmax vs the true next token,
    over windows of length `ctx_len`. Reset positions are skipped."""
    bs = model.cfg.block_size
    ctx_len = min(ctx_len, bs)
    xs, ys = [], []
    for j in range(ctx_len - 1, len(seq) - 1):
        if (j + 1) % 257 == 0:
            continue  # corpus resets are unpredictable; don't score them
        xs.append(seq[j - ctx_len + 1 : j + 1])
        ys.append(seq[j + 1])
        if len(xs) >= max_samples:
            break
    if not xs:
        return float("nan")
    correct = 0
    for i in range(0, len(xs), 256):
        xb = torch.tensor(np.stack(xs[i : i + 256]), dtype=torch.long)
        pred = model(xb)[0][:, -1, :].argmax(-1).numpy()
        correct += int((pred == np.array(ys[i : i + 256])).sum())
    return correct / len(xs)


@torch.no_grad()
def split_acc(model, orb: np.ndarray, seen: set, ctx_len: int, max_samples: int):
    """Accuracy on the fresh orbit, split by whether the ending (a,b) state was
    seen in training. Accuracy on UNSEEN states is the true generalisation test."""
    ctx_len = min(ctx_len, model.cfg.block_size)
    groups = {True: [[], []], False: [[], []]}  # is_seen -> [windows, targets]
    for j in range(ctx_len - 1, len(orb) - 1):
        k = (int(orb[j - 1]), int(orb[j])) in seen
        if len(groups[k][0]) >= max_samples:
            continue
        groups[k][0].append(orb[j - ctx_len + 1 : j + 1])
        groups[k][1].append(orb[j + 1])
    res = {}
    for k, (xs, ys) in groups.items():
        if not xs:
            res[k] = (float("nan"), 0)
            continue
        correct = 0
        for i in range(0, len(xs), 256):
            xb = torch.tensor(np.stack(xs[i : i + 256]), dtype=torch.long)
            pred = model(xb)[0][:, -1, :].argmax(-1).numpy()
            correct += int((pred == np.array(ys[i : i + 256])).sum())
        res[k] = (correct / len(xs), len(xs))
    return res


def fresh_orbit(table: np.ndarray, vocab: int, n: int, s0: int, s1: int) -> np.ndarray:
    d = [s0 % vocab, s1 % vocab]
    for i in range(2, n):
        d.append(int((d[i - 2] + table[d[i - 1]]) % vocab))
    return np.array(d, dtype=np.int64)


def evaluate(ckpt: str, seed: int, toy_tokens: int, val_frac: float, samples: int) -> dict:
    model, _, step = m.load_checkpoint(ckpt, "cpu")
    model.eval()
    model.cfg.capacity_factor = 1e9  # measure the learned mapping, not the capacity-drop artifact
    vocab = model.cfg.vocab_size
    bs = model.cfg.block_size

    data = m.make_toy_corpus(toy_tokens, vocab_size=vocab, seed=seed).numpy()
    train_data, val_data = m.split_train_val(torch.from_numpy(data), val_frac)
    train_data, val_data = train_data.numpy(), val_data.numpy()
    table = rule_table(seed, vocab)

    # a never-seen orbit (same rule/table, different start) — primary generalisation test
    orb = fresh_orbit(table, vocab, 1500, s0=41, s1=7)

    # cross-entropy on val (standard LM metric)
    metrics = m.estimate_loss(model, torch.from_numpy(train_data), torch.from_numpy(val_data),
                              batch_size=16, eval_iters=20, device="cpu")

    # accuracy on the new orbit at several context lengths. The headline is the
    # BEST length: a model trained at sequence length T only saw RoPE positions
    # 0..T-1, so evaluating beyond T is position-extrapolation, not a learning
    # failure. The peak is the fair, training-length-agnostic quality metric.
    sweep = {L: batched_acc(model, orb, L, samples) for L in (2, 8, 16, 32, bs)}
    best_L = max(sweep, key=sweep.get)

    # true-generalisation breakdown: how many (a,b) states did training cover, and
    # what is accuracy on states the model never trained on?
    seen = set((int(train_data[j - 1]), int(train_data[j])) for j in range(1, len(train_data)))
    split = split_acc(model, orb, seen, best_L, samples)

    out = {
        "step": step,
        "val_ce": metrics["val_loss"],
        "val_ppl": float(np.exp(metrics["val_loss"])),
        "best_L": best_L,
        "acc_train": batched_acc(model, train_data, best_L, samples),
        "acc_val": batched_acc(model, val_data, best_L, samples),
        "acc_neworbit": sweep[best_L],
        "ctx_sweep": sweep,
        "state_coverage": len(seen) / (vocab * vocab),
        "acc_seen": split[True][0],
        "acc_unseen": split[False][0],
        "n_unseen": split[False][1],
    }
    return out


def show(name: str, r: dict) -> None:
    print(f"\n=== {name}  (step {r['step']}) ===")
    print(f"  val cross-entropy   : {r['val_ce']:.4f}   (perplexity {r['val_ppl']:.2f}; random CE = {np.log(64):.2f})")
    print(f"  accuracy at best context length ({r['best_L']} tokens; random = 1.6%):")
    print(f"    train orbit       : {100*r['acc_train']:5.1f}%")
    print(f"    val   orbit       : {100*r['acc_val']:5.1f}%")
    print(f"    new   orbit       : {100*r['acc_neworbit']:5.1f}%   <- overall rule-fit (mostly recall, see below)")
    sweep = "  ".join(f"{L}:{100*a:.0f}%" for L, a in r["ctx_sweep"].items())
    print(f"  new-orbit acc by context length: {sweep}")
    print(f"  TRUE generalisation (training covered {100*r['state_coverage']:.0f}% of the 4096 (a,b) states):")
    print(f"    on states SEEN in training   : {100*r['acc_seen']:5.1f}%   (recall)")
    print(f"    on states UNSEEN in training : {100*r['acc_unseen']:5.1f}%   (extrapolation; n={r['n_unseen']})  <- the real test")


def main() -> None:
    ap = argparse.ArgumentParser(description="Evaluate how well a checkpoint learned the toy rule.")
    ap.add_argument("--ckpt", default="moe.pt")
    ap.add_argument("--compare", default=None, help="second checkpoint to compare against")
    ap.add_argument("--seed", type=int, default=123, help="corpus seed (must match training)")
    ap.add_argument("--toy-tokens", type=int, default=20_000)
    ap.add_argument("--val-frac", type=float, default=0.1)
    ap.add_argument("--samples", type=int, default=2000)
    args = ap.parse_args()

    a = evaluate(args.ckpt, args.seed, args.toy_tokens, args.val_frac, args.samples)
    show(args.ckpt, a)

    if args.compare:
        b = evaluate(args.compare, args.seed, args.toy_tokens, args.val_frac, args.samples)
        show(args.compare, b)
        # verdict: prefer higher OOD accuracy, tie-break on lower val CE
        da = a["acc_neworbit"] - b["acc_neworbit"]
        print("\n=== verdict ===")
        if abs(da) >= 0.01:
            winner = args.ckpt if da > 0 else args.compare
            print(f"  {winner} is better: new-orbit accuracy higher by {abs(da)*100:.1f} points")
        else:
            winner = args.ckpt if a["val_ce"] < b["val_ce"] else args.compare
            print(f"  ~tie on accuracy; {winner} has lower val cross-entropy")


if __name__ == "__main__":
    main()
